-- ─────────────────────────────────────────────────────────────────────────
-- Append-only enforcement (CLAUDE.md invariant 1, phase brief item 1:
-- "Enforce it at the database level (a trigger or rule rejecting
-- UPDATE/DELETE) as well as in code").
--
-- A BEFORE trigger on each of UPDATE and DELETE, rather than one trigger with
-- two events, so the error message can name the operation that was attempted.
--
-- Row-level triggers deliberately: they do NOT fire on TRUNCATE, which is what
-- `tests/setup/reset.ts` uses between tests (docs/TESTING.md §2). A statement
-- trigger on TRUNCATE would make the entire integration suite unrunnable while
-- protecting nothing — production never truncates.
--
-- Corrections are REVERSAL rows (SPEC §4). The exception text says so, because
-- the person who trips this is a developer who needs to be told where to go
-- next, not just told "no".
-- ─────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION ledger_entries_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION
        'ledger_entries is append-only: % is not permitted. Insert a REVERSAL entry instead.',
        TG_OP
        USING ERRCODE = 'P0001';
END;
$$;

CREATE TRIGGER ledger_entries_no_update
    BEFORE UPDATE ON "ledger_entries"
    FOR EACH ROW EXECUTE FUNCTION ledger_entries_append_only();

CREATE TRIGGER ledger_entries_no_delete
    BEFORE DELETE ON "ledger_entries"
    FOR EACH ROW EXECUTE FUNCTION ledger_entries_append_only();

-- ─────────────────────────────────────────────────────────────────────────
-- Partial unique indexes. Each one turns a business rule the phase brief
-- states into something two concurrent transactions cannot both violate.
-- ─────────────────────────────────────────────────────────────────────────

-- "Approving twice must not double-pay" (phase brief item 3). One EARNING per
-- task, for all time. A task can only reach APPROVED once — SPEC §5.1 lets it
-- leave only for DONE or CANCELLED — so this constrains nothing legitimate.
CREATE UNIQUE INDEX "ledger_entries_one_earning_per_task"
    ON "ledger_entries" ("taskId")
    WHERE "type" = 'EARNING';

-- "one SALARY entry per salaried worker per cycle" (phase brief item 4). This
-- is also what makes the accrual half of the close job idempotent: a second run
-- cannot write a second month's salary, whatever the code does.
CREATE UNIQUE INDEX "ledger_entries_one_salary_per_cycle"
    ON "ledger_entries" ("userId", "cycleId")
    WHERE "type" = 'SALARY';

-- At most one OPEN cycle. Two would mean two answers to "which cycle does this
-- entry belong to", and the second close would silently pay a different set of
-- entries than the first.
CREATE UNIQUE INDEX "payout_cycles_single_open"
    ON "payout_cycles" (("status"))
    WHERE "status" = 'OPEN';
