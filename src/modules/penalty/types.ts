export interface MoneyRegisterPageDto {
  items: MoneyRegisterRowDto[]
  total: number
  page: number
  pageSize: number
  /** Magnitudes over everything the filters select, not just this page. */
  totalPenalties: string
  totalBonuses: string
  /** Penalties already reversed, so the net figure below can be explained. */
  totalReversed: string
  /** `totalPenalties − totalReversedPenalties`: what the organization actually retained. */
  netPenalties: string
}

/** The task sheet's panel: what this task has cost, per delivery (SPEC T4). */
export interface TaskPenaltyPanelDto {
  taskId: string
  /** The live figure, recomputed now. Null when nothing is or would be owed. */
  current: PenaltyBreakdownDto | null
  /** Why `current` is null, when it is. */
  currentStatus: 'DUE' | 'NOT_LATE' | 'ZERO' | 'NO_BASIS' | 'NO_ASSIGNEE'
  /** Every automatic PENALTY row on this task, newest first, with its round. */
  entries: PenaltyEntryDto[]
  /** Sum of the unreversed automatic penalties — what the task has actually cost. */
  totalCharged: string
  revisionCount: number
  /** False when SPEC T4's flag is off for this project (phase brief item 4). */
  penalizeRevisionLateness: boolean
}

export interface PenaltyProfileDto {
  id: string
  name: string
  mode: PenaltyMode
  /** Currency for `FIXED_*`, a percentage for `PCT_*`. */
  value: string
  graceHours: number | null
  /** How many منفّذين this formula currently applies to. */
  userCount: number
  createdAt: Date
}

/** What one recomputation did. Returned by the service and summed by the job. */
export type PenaltyRecomputeOutcome =
  /** The figure was already right. The idempotent case, and the common one. */
  | 'unchanged'
  /** A first penalty was inserted. */
  | 'applied'
  /** A REVERSAL and a fresh PENALTY were inserted (SPEC §5.4). */
  | 'recalculated'
  /** A REVERSAL was inserted and nothing replaced it — lateness reached zero. */
  | 'cleared'
  /** Nothing was owed and nothing existed. */
  | 'none'
  /** Not computable: no assignee, no basis, or the task is not penalisable. */
  | 'skipped'
  /** Another writer holds this task's lock. Their answer will be the same one. */
  | 'locked'

export interface PenaltyRecomputeResult {
  taskId: string
  outcome: PenaltyRecomputeOutcome
  /** Set for `skipped`, so the audit row says which figure was missing. */
  skipReason: 'no-assignee' | 'no-basis' | 'not-penalisable' | 'assignee-deleted' | null
  /** The REVERSAL that was written, if any. */
  reversedEntryId: string | null
  /** The new PENALTY that was written, if any. */
  entryId: string | null
  /** What the ledger now holds for the current round. `0.00` when cleared. */
  amount: string
  breakdown: PenaltyBreakdownDto | null
}

export interface PenaltyJobResult {
  scanned: number
  applied: number
  recalculated: number
  cleared: number
  unchanged: number
  skipped: number
  locked: number
  failed: number
  /** True when the per-run backstop stopped the sweep before the work ran out. */
  truncated: boolean
}
