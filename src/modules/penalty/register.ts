/**
 * modules/penalty/register — the read paths behind phase brief items 9 and 10.
 *
 * Every figure here is a `SUM` over `ledger_entries` (CLAUDE.md invariant 1).
 * Nothing is cached, nothing is denormalised, and there is no "total penalties"
 * column anywhere — which is what makes the register, the task sheet, the
 * منفّذ's statement and the payout breakdown incapable of disagreeing.
 */

type DecimalLike = { toFixed(dp: number): string }

const moneyOf = (value: DecimalLike | null | undefined): Money =>
  value == null ? zero() : toMoney(value.toFixed(2))

const magnitude = (value: DecimalLike | null | undefined): string =>
  toStorageString(abs(moneyOf(value)))

// ─────────────────────────────────────────────────────────────────────────────
// The manager's register
// ─────────────────────────────────────────────────────────────────────────────

const REGISTER_SELECT = {
  id: true,
  userId: true,
  type: true,
  amount: true,
  note: true,
  taskId: true,
  isAutoGenerated: true,
  createdAt: true,
  user: { select: { id: true, fullName: true } },
  task: { select: { id: true, title: true } },
  createdBy: { select: { id: true, fullName: true } },
  reversedBy: { select: { id: true, note: true } },
} as const

export interface ListMoneyRegisterArgs extends ListMoneyRegisterInput {
  /** Extra where-fragment from the RBAC scope (`queries.ts`). */
  scope?: Record<string, unknown>
}

function registerWhere(args: ListMoneyRegisterArgs): Record<string, unknown> {
  return {
    ...(args.scope ?? {}),
    type: args.kind ? args.kind : { in: ['PENALTY', 'BONUS'] },
    ...(args.userId ? { userId: args.userId } : {}),
    ...(args.taskId ? { taskId: args.taskId } : {}),
    ...(args.projectId ? { task: { projectId: args.projectId } } : {}),
    ...(args.automatic ? { isAutoGenerated: args.automatic === 'auto' } : {}),
    ...(args.reversed
      ? args.reversed === 'reversed'
        ? { reversedBy: { isNot: null } }
        : { reversedBy: { is: null } }
      : {}),
    ...(args.from || args.to
      ? {
          createdAt: {
            ...(args.from ? { gte: args.from } : {}),
            ...(args.to ? { lt: args.to } : {}),
          },
        }
      : {}),
  }
}

export async function listMoneyRegister(
  db: Db,
  args: ListMoneyRegisterArgs,
): Promise<MoneyRegisterPageDto> {
  const where = registerWhere(args)
  const page = Math.max(1, args.page)
  const pageSize = Math.min(200, Math.max(1, args.pageSize))

  const [rows, total, byType, reversedPenalties] = await Promise.all([
    db.ledgerEntry.findMany({
      where,
      // `id` breaks the tie: a frozen clock in a test, or one recomputation
      // writing a reversal and a replacement, produces identical `createdAt`s.
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      skip: (page - 1) * pageSize,
      take: pageSize,
      select: REGISTER_SELECT,
    }),
    db.ledgerEntry.count({ where }),
    // Totals over everything the filters select, not over this page — the
    // question a register's footer answers is "how much, in total, matched".
    db.ledgerEntry.groupBy({ by: ['type'], _sum: { amount: true }, where }),
    db.ledgerEntry.aggregate({
      _sum: { amount: true },
      where: { ...where, type: 'PENALTY', reversedBy: { isNot: null } },
    }),
  ])

  const totals = new Map(
    (
      byType as unknown as Array<{ type: string; _sum: { amount: DecimalLike | null } }>
    ).map((row) => [row.type, moneyOf(row._sum.amount)]),
  )

  const penalties = abs(totals.get('PENALTY') ?? zero())
  const reversed = abs(moneyOf(reversedPenalties._sum.amount as DecimalLike | null))

  return {
    items: (rows as unknown as RegisterRow[]).map(toRegisterRow),
    total,
    page,
    pageSize,
    totalPenalties: toStorageString(penalties),
    totalBonuses: toStorageString(abs(totals.get('BONUS') ?? zero())),
    totalReversed: toStorageString(reversed),
    // What the agency actually retained. Stated separately from the gross rather
    // than instead of it: a manager auditing a month needs to see both the
    // deductions that were applied and the ones that were undone.
    netPenalties: toStorageString(sub(penalties, reversed)),
  }
}

interface RegisterRow {
  id: string
  userId: string
  type: string
  amount: DecimalLike
  note: string
  taskId: string | null
  isAutoGenerated: boolean
  createdAt: Date
  user: { id: string; fullName: string } | null
  task: { id: string; title: string } | null
  createdBy: { id: string; fullName: string } | null
  reversedBy: { id: string; note: string } | null
}

function toRegisterRow(row: RegisterRow): MoneyRegisterRowDto {
  return {
    entryId: row.id,
    kind: row.type as 'PENALTY' | 'BONUS',
    userId: row.userId,
    userFullName: row.user?.fullName ?? '',
    taskId: row.taskId,
    taskTitle: row.task?.title ?? null,
    amount: magnitude(row.amount),
    note: row.note,
    isAutoGenerated: row.isAutoGenerated,
    createdAt: row.createdAt,
    createdByName: row.createdBy?.fullName ?? null,
    reversedByEntryId: row.reversedBy?.id ?? null,
    reversalReason: row.reversedBy?.note ?? null,
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// The task sheet's panel (phase brief item 9)
// ─────────────────────────────────────────────────────────────────────────────

export interface TaskPenaltyPanelArgs {
  taskId: string
  calendar: Calendar
  settings: PenaltySettings
  now: Date
}

/**
 * What this task has cost, and why — per delivery (SPEC T4).
 *
 * The live round is **recomputed rather than read**, so a manager opening the
 * sheet at noon sees the deduction as it stands at noon rather than as it stood
 * at 03:00. Reading is a pure function here: nothing is written, so looking at
 * a penalty never creates one.
 *
 * Rows that a later revision froze are labelled with the round they belong to,
 * derived from the activity feed exactly as the engine derives it — so the
 * panel cannot disagree with the entries it is describing.
 */
export async function taskPenaltyPanel(
  db: Db,
  args: TaskPenaltyPanelArgs,
): Promise<TaskPenaltyPanelDto> {
  const task = await db.task.findFirst({
    where: { id: args.taskId, deletedAt: null, project: { deletedAt: null } },
    select: { id: true },
  })
  if (!task) throw new NotFoundError('Task', args.taskId)

  const assessment = await assessTaskPenalty(db, {
    taskId: args.taskId,
    calendar: args.calendar,
    settings: args.settings,
    now: args.now,
  })

  const rows = await db.ledgerEntry.findMany({
    where: { taskId: args.taskId, type: 'PENALTY' },
    orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
    select: {
      id: true,
      userId: true,
      amount: true,
      note: true,
      isAutoGenerated: true,
      createdAt: true,
      user: { select: { fullName: true } },
      createdBy: { select: { id: true, fullName: true } },
      task: { select: { title: true } },
      reversedBy: { select: { id: true, note: true, createdAt: true } },
    },
  })

  const rounds = revisionRoundsFromActivity(
    await db.taskActivity.findMany({
      where: { taskId: args.taskId, type: 'STATUS_CHANGED', to: 'REVISION_REQUESTED' },
      orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
      select: { type: true, from: true, to: true, createdAt: true },
    }),
  )

  const entries: PenaltyEntryDto[] = (rows as unknown as PanelRow[]).map((row) => ({
    entryId: row.id,
    userId: row.userId,
    userFullName: row.user?.fullName ?? '',
    taskId: args.taskId,
    taskTitle: row.task?.title ?? null,
    amount: magnitude(row.amount),
    note: row.note,
    isAutoGenerated: row.isAutoGenerated,
    createdAt: row.createdAt,
    createdById: row.createdBy?.id ?? null,
    createdByName: row.createdBy?.fullName ?? null,
    reversedByEntryId: row.reversedBy?.id ?? null,
    reversedAt: row.reversedBy?.createdAt ?? null,
    reversalReason: row.reversedBy?.note ?? null,
    // A manual deduction belongs to no delivery — it was somebody's decision,
    // not an accrual against a deadline — so it carries no round label.
    roundIndex: row.isAutoGenerated ? roundIndexAt(row.createdAt, rounds) : null,
    isCurrentRound: row.isAutoGenerated && isInCurrentRound(row.createdAt, rounds),
  }))

  const charged = entries
    .filter((e) => e.reversedByEntryId === null)
    .reduce<Money>((acc, e) => add(acc, e.amount), zero())

  return {
    taskId: args.taskId,
    current: assessment.breakdown,
    currentStatus:
      assessment.skipReason === 'no-assignee'
        ? 'NO_ASSIGNEE'
        : assessment.skipReason === 'no-basis'
          ? 'NO_BASIS'
          : assessment.calculation.status,
    entries,
    totalCharged: toStorageString(charged),
    revisionCount: assessment.revisionCount,
    penalizeRevisionLateness: assessment.penalizeRevisionLateness,
  }
}

interface PanelRow {
  id: string
  userId: string
  amount: DecimalLike
  note: string
  isAutoGenerated: boolean
  createdAt: Date
  user: { fullName: string } | null
  createdBy: { id: string; fullName: string } | null
  task: { title: string } | null
  reversedBy: { id: string; note: string; createdAt: Date } | null
}

// ─────────────────────────────────────────────────────────────────────────────
// SPEC R4 — deductions as agency income (phase brief item 10)
// ─────────────────────────────────────────────────────────────────────────────

export interface DeductionsReportRow {
  key: string
  label: string
  /** Gross deductions applied in the period, as a positive magnitude. */
  penalties: string
  /** Deductions later reversed, as a positive magnitude. */
  reversed: string
  /** `penalties − reversed`: what the agency actually retained. */
  net: string
  count: number
}

export interface DeductionsReportDto {
  from: Date
  to: Date
  groupBy: DeductionsReportInput['groupBy']
  rows: DeductionsReportRow[]
  totalPenalties: string
  totalReversed: string
  totalNet: string
}

/**
 * SPEC §1: "Deductions are reported as agency income in reports only. **No
 * profit/margin math anywhere.**"
 *
 * That second sentence is a constraint on this function specifically, and it is
 * kept by omission rather than by comment: there is no revenue figure here, no
 * cost figure, no ratio and no percentage-of-anything. The report answers one
 * question — how much was deducted in this period, and how much of that was
 * given back — and deliberately gives a reader nothing to divide.
 *
 * Reversals are shown beside the gross rather than netted silently into it. A
 * month with 10,000 deducted and 9,000 reversed is a very different month from
 * one with 1,000 deducted, and a single net figure would make them identical.
 */
export async function deductionsReport(
  db: Db,
  args: DeductionsReportInput & { scope?: Record<string, unknown> },
): Promise<DeductionsReportDto> {
  const where = {
    ...(args.scope ?? {}),
    type: 'PENALTY' as const,
    createdAt: { gte: args.from, lt: args.to },
  }

  const rows = await db.ledgerEntry.findMany({
    where,
    select: {
      id: true,
      amount: true,
      createdAt: true,
      userId: true,
      cycleId: true,
      user: { select: { fullName: true } },
      task: { select: { projectId: true, project: { select: { name: true } } } },
      cycle: { select: { periodStart: true, periodEnd: true } },
      reversedBy: { select: { id: true } },
    },
  })

  const buckets = new Map<
    string,
    { label: string; gross: Money; back: Money; n: number }
  >()

  for (const row of rows as unknown as ReportRow[]) {
    const { key, label } = bucketFor(row, args.groupBy)
    const bucket = buckets.get(key) ?? { label, gross: zero(), back: zero(), n: 0 }
    const amount = abs(moneyOf(row.amount))

    bucket.gross = add(bucket.gross, amount)
    if (row.reversedBy !== null) bucket.back = add(bucket.back, amount)
    bucket.n += 1
    buckets.set(key, bucket)
  }

  const reportRows: DeductionsReportRow[] = [...buckets]
    .map(([key, bucket]) => ({
      key,
      label: bucket.label,
      penalties: toStorageString(bucket.gross),
      reversed: toStorageString(bucket.back),
      net: toStorageString(sub(bucket.gross, bucket.back)),
      count: bucket.n,
    }))
    .sort((a, b) => a.key.localeCompare(b.key))

  const totalGross = reportRows.reduce<Money>((acc, r) => add(acc, r.penalties), zero())
  const totalBack = reportRows.reduce<Money>((acc, r) => add(acc, r.reversed), zero())

  return {
    from: args.from,
    to: args.to,
    groupBy: args.groupBy,
    rows: reportRows,
    totalPenalties: toStorageString(totalGross),
    totalReversed: toStorageString(totalBack),
    totalNet: toStorageString(sub(totalGross, totalBack)),
  }
}

interface ReportRow {
  id: string
  amount: DecimalLike
  createdAt: Date
  userId: string
  cycleId: string | null
  user: { fullName: string } | null
  task: { projectId: string; project: { name: string } | null } | null
  cycle: { periodStart: Date; periodEnd: Date } | null
  reversedBy: { id: string } | null
}

/** Cairo month key, so a deduction at 01:00 on the 1st is not last month's. */
const cairoMonthKey = (at: Date): string =>
  new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Africa/Cairo',
    year: 'numeric',
    month: '2-digit',
  })
    .format(at)
    .slice(0, 7)

function bucketFor(
  row: ReportRow,
  groupBy: DeductionsReportInput['groupBy'],
): { key: string; label: string } {
  if (groupBy === 'cycle') {
    return {
      key: row.cycleId ?? 'none',
      label: row.cycle ? cairoMonthKey(row.cycle.periodEnd) : '—',
    }
  }
  if (groupBy === 'project') {
    return {
      key: row.task?.projectId ?? 'none',
      label: row.task?.project?.name ?? '—',
    }
  }
  if (groupBy === 'worker') {
    return { key: row.userId, label: row.user?.fullName ?? '—' }
  }
  const month = cairoMonthKey(row.createdAt)
  return { key: month, label: month }
}
