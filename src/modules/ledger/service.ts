const ROW_SELECT = {
  ...ENTRY_SELECT,
  task: { select: { id: true, title: true } },
  createdBy: { select: { id: true, fullName: true, username: true } },
  reversedBy: { select: { id: true } },
} as const

export interface ListEntriesArgs {
  userId?: string
  cycleId?: string
  type?: LedgerType
  taskId?: string
  from?: Date
  to?: Date
  page?: number
  pageSize?: number
  /** Extra where-fragment from the RBAC scope (`queries.ts`). */
  scope?: Record<string, unknown>
}

const DEFAULT_PAGE_SIZE = 50
const MAX_PAGE_SIZE = 200

export async function listEntries(db: Db, args: ListEntriesArgs): Promise<LedgerPageDto> {
  const page = Math.max(1, args.page ?? 1)
  const pageSize = Math.min(
    MAX_PAGE_SIZE,
    Math.max(1, args.pageSize ?? DEFAULT_PAGE_SIZE),
  )

  const where = {
    ...(args.scope ?? {}),
    ...(args.userId ? { userId: args.userId } : {}),
    ...(args.cycleId ? { cycleId: args.cycleId } : {}),
    ...(args.type ? { type: args.type } : {}),
    ...(args.taskId ? { taskId: args.taskId } : {}),
    ...(args.from || args.to
      ? {
          createdAt: {
            ...(args.from ? { gte: args.from } : {}),
            ...(args.to ? { lt: args.to } : {}),
          },
        }
      : {}),
  }

  const [rows, total, totals] = await Promise.all([
    db.ledgerEntry.findMany({
      where,
      // `id` breaks the tie: a frozen clock in a test, or a close writing many
      // entries in one transaction, produces identical `createdAt` values.
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      skip: (page - 1) * pageSize,
      take: pageSize,
      select: ROW_SELECT,
    }),
    db.ledgerEntry.count({ where }),
    // The sum of everything the filters select, not of the page — and not,
    // deliberately, "the caller's balance". Those coincide on the مستحقاتي page
    // (one منفّذ, no filters), and where they do not, a figure that answered a
    // question nobody asked would be worse than one that answers this one.
    db.ledgerEntry.aggregate({ _sum: { amount: true }, where }),
  ])

  return {
    items: (rows as unknown as Array<EntryRow & Record<string, unknown>>).map((row) => ({
      ...toDto(row),
      task: (row.task as { id: string; title: string } | null) ?? null,
      createdBy:
        (row.createdBy as { id: string; fullName: string; username: string } | null) ??
        null,
      reversedByEntryId: (row.reversedBy as { id: string } | null)?.id ?? null,
    })) satisfies LedgerEntryRowDto[],
    total,
    page,
    pageSize,
    balance: toStorageString(moneyOf(totals._sum.amount as DecimalLike | null)),
  }
}

export async function getEntry(db: Db, id: string): Promise<LedgerEntryDto> {
  const row = (await db.ledgerEntry.findUnique({
    where: { id },
    select: ENTRY_SELECT,
  })) as EntryRow | null
  if (!row) throw new NotFoundError('LedgerEntry', id)
  return toDto(row)
}

/**
 * Per-type totals for one cycle. The building block of both the payout
 * breakdown and the مستحقاتي "this cycle so far" panel, so that the two can
 * never disagree about what a cycle contained.
 */
export async function cycleTotalsByType(
  db: Db,
  args: { userId: string; cycleId: string },
): Promise<Map<LedgerType, Money>> {
  const grouped = await db.ledgerEntry.groupBy({
    by: ['type'],
    _sum: { amount: true },
    where: { userId: args.userId, cycleId: args.cycleId },
  })
  const rows = grouped as unknown as Array<{
    type: string
    _sum: { amount: DecimalLike | null }
  }>

  return new Map(rows.map((row) => [row.type as LedgerType, moneyOf(row._sum.amount)]))
}

export async function summaryFor(
  db: Db,
  args: { userId: string },
): Promise<LedgerSummaryDto> {
  const [balance, open, outstanding] = await Promise.all([
    balanceFor(db, { userId: args.userId }),
    db.payoutCycle.findFirst({
      where: { status: 'OPEN' },
      orderBy: { periodStart: 'desc' },
      select: { id: true, periodStart: true, periodEnd: true },
    }),
    db.payout.findMany({
      where: { userId: args.userId, status: { in: ['DRAFT', 'APPROVED'] } },
      select: { net: true, paidAmount: true },
    }),
  ])

  const outstandingTotal = outstanding.reduce(
    (acc, row) => acc.plus(moneyOf(row.net)).minus(moneyOf(row.paidAmount)),
    zero(),
  )

  const totals = open
    ? await cycleTotalsByType(db, { userId: args.userId, cycleId: open.id })
    : null

  const magnitude = (type: LedgerType): string =>
    toStorageString((totals?.get(type) ?? zero()).abs())

  return {
    userId: args.userId,
    balance,
    currentCycle:
      open && totals
        ? {
            id: open.id,
            periodStart: open.periodStart,
            periodEnd: open.periodEnd,
            gross: toStorageString(
              (totals.get('EARNING') ?? zero()).plus(totals.get('SALARY') ?? zero()),
            ),
            earnings: magnitude('EARNING'),
            salary: magnitude('SALARY'),
            penalties: magnitude('PENALTY'),
            bonuses: magnitude('BONUS'),
            advances: magnitude('ADVANCE'),
            adjustments: toStorageString(totals.get('ADJUSTMENT') ?? zero()),
          }
        : null,
    outstandingPayouts: toStorageString(outstandingTotal),
  }
}

