export interface ReverseEntryArgs {
  entryId: string
  /** Mandatory. It becomes the reversal's own note, which the منفّذ reads. */
  reason: string
  actor: AuditActorRef | null
  cycleDay: number
  at?: Date
  ip?: string
  isAutoGenerated?: boolean
}

/**
 * Insert the opposite of an entry. Never touches the original.
 *
 * Three things are refused, and each one is a rule rather than a precaution:
 *
 *  - **Reversing twice.** Checked here and enforced by a unique index on
 *    `reversesEntryId`, so two concurrent callers cannot both succeed.
 *  - **Reversing a reversal.** That is a re-application, not a correction, and
 *    it would make the audit trail read backwards. Write a fresh entry.
 *  - **Reversing anything already paid out.** Money that has left the agency
 *    cannot be un-charged by rewriting the period it came from
 *    (docs/TESTING.md §4 axis 7). The instrument for that is an `ADJUSTMENT` in
 *    the open cycle, which shows up as its own movement on the next statement.
 *
 * A *closed but unpaid* cycle is reversible on purpose: SPEC §5.4's penalty
 * recomputation ("insert REVERSAL + insert new PENALTY") has to keep working
 * across a cycle boundary. The reversal lands in the open cycle, so the closed
 * statement stays exactly as the منفّذ read it.
 */
export async function reverseEntry(
  db: Db,
  args: ReverseEntryArgs,
): Promise<LedgerEntryDto> {
  const reason = args.reason.trim()
  if (!reason) throw new DomainError('ledger.errors.reasonRequired')

  const original = (await db.ledgerEntry.findUnique({
    where: { id: args.entryId },
    select: ENTRY_SELECT,
  })) as EntryRow | null
  if (!original) throw new NotFoundError('LedgerEntry', args.entryId)

  if (original.type === 'REVERSAL') {
    throw new DomainError('ledger.errors.cannotReverseReversal', { entryId: original.id })
  }

  /**
   * A `PAYOUT` is the one entry that is not a standalone movement: it is the
   * ledger's half of a `Payout` row whose `paidAmount` is a running total.
   * Reversing it would credit the balance back while `paidAmount` kept saying
   * the money had gone — breaking the invariant `markPayoutPaid` maintains
   * ("the `PAYOUT` entries for a (منفّذ, cycle) always sum to exactly
   * `−paidAmount`") and leaving no record that agrees with any other.
   *
   * Cash that left the agency and came back is a new movement, not the undoing
   * of an old one: record it as an `ADJUSTMENT`.
   */
  if (original.type === 'PAYOUT') {
    throw new DomainError('ledger.errors.cannotReversePayout', { entryId: original.id })
  }

  const existing = await db.ledgerEntry.findUnique({
    where: { reversesEntryId: original.id },
    select: { id: true },
  })
  if (existing) {
    throw new ConflictError('ledger.errors.alreadyReversed', { entryId: original.id })
  }

  if (original.cycleId) {
    const paid = await db.payout.findFirst({
      where: { userId: original.userId, cycleId: original.cycleId, status: 'PAID' },
      select: { id: true },
    })
    if (paid) {
      throw new DomainError('ledger.errors.cycleAlreadyPaid', {
        entryId: original.id,
        cycleId: original.cycleId,
      })
    }
  }

  try {
    return await appendEntry(db, {
      userId: original.userId,
      type: 'REVERSAL',
      amount: negate(moneyOf(original.amount)),
      note: reason,
      taskId: original.taskId,
      reversesEntryId: original.id,
      isAutoGenerated: args.isAutoGenerated ?? false,
      actor: args.actor,
      cycleDay: args.cycleDay,
      auditAction: 'ledger.reversed',
      reason,
      ...(args.at ? { at: args.at } : {}),
      ...(args.ip ? { ip: args.ip } : {}),
    })
  } catch (error) {
    /**
     * The check above is a read-then-write, so two callers can both pass it and
     * `ledger_entries_reversesEntryId_key` catches the second. That is the
     * index doing its job — but the *error* was escaping as a raw Prisma
     * `P2002`, which carries an index name and cannot be rendered in Arabic.
     *
     * Mapped in Phase 8 rather than earlier because Phase 8 is what makes the
     * race ordinary: the penalty engine now reverses its own figures while a
     * manager may be reversing the same one by hand, every night. Before it,
     * two humans would have had to click within milliseconds of each other.
     *
     * The result is that the guard and the index give the *same* answer, so a
     * manager reads "هذا القيد معكوس بالفعل" whichever one caught them.
     */
    if (isUniqueViolation(error)) {
      throw new ConflictError('ledger.errors.alreadyReversed', { entryId: original.id })
    }
    throw error
  }
}

