export interface AppendEntryArgs {
  userId: string
  type: LedgerType
  /** Signed. Validated against the type's direction before anything is written. */
  amount: MoneyInput
  /** Arabic prose the منفّذ reads on their statement. Never an id pair. */
  note: string
  /** Null for scheduler/system writes, matching `AuditLog.actorId`. */
  actor: AuditActorRef | null
  /**
   * Settings `payout.cycleDay`. Injected rather than read here, per CLAUDE.md
   * invariant 4 — only consulted when there is no open cycle to attach to.
   */
  cycleDay: number
  taskId?: string | null
  /**
   * Explicit attribution. Pass it when the movement belongs to a cycle other
   * than the open one — a salary accrued *into* the cycle being closed, or a
   * payment settling one that closed last week.
   */
  cycleId?: string | null
  isAutoGenerated?: boolean
  reversesEntryId?: string | null
  at?: Date
  ip?: string
  /** Defaults to `ledger.entryCreated`; reversals and advances name themselves. */
  auditAction?: string
  reason?: string
}

/**
 * Append one entry. There is no update or delete counterpart, by design.
 *
 * The audit row is written in the same call, and with the same `db` — which may
 * be a transaction client. That is the point: the money and the record of who
 * moved it commit together or not at all (CLAUDE.md invariant 7).
 */
export async function appendEntry(
  db: Db,
  args: AppendEntryArgs,
): Promise<LedgerEntryDto> {
  const at = args.at ?? new Date()
  const amount = toMoney(args.amount)
  assertSignForType(args.type, amount)

  const note = args.note.trim()
  if (!note) throw new DomainError('ledger.errors.noteRequired', { type: args.type })

  // Soft-delete is respected on the *write* side too (CLAUDE.md invariant 8):
  // a departed منفّذ's history stays readable, but nothing new accrues to it.
  const user = await db.user.findFirst({
    where: { id: args.userId, deletedAt: null },
    select: { id: true },
  })
  if (!user) throw new NotFoundError('User', args.userId)

  const cycleId =
    args.cycleId !== undefined
      ? args.cycleId
      : (await ensureOpenCycle(db, { now: at, cycleDay: args.cycleDay })).id

  const row = (await db.ledgerEntry.create({
    data: {
      userId: args.userId,
      cycleId,
      type: args.type,
      amount: toStorageString(amount),
      taskId: args.taskId ?? null,
      note,
      isAutoGenerated: args.isAutoGenerated ?? false,
      reversesEntryId: args.reversesEntryId ?? null,
      createdById: args.actor?.id ?? null,
      createdAt: at,
    },
    select: ENTRY_SELECT,
  })) as EntryRow

  await recordAudit(db, {
    actor: args.actor,
    action: args.auditAction ?? 'ledger.entryCreated',
    entity: 'LedgerEntry',
    entityId: row.id,
    after: {
      userId: row.userId,
      type: row.type,
      amount: row.amount.toFixed(2),
      cycleId: row.cycleId,
      taskId: row.taskId,
      note: row.note,
      isAutoGenerated: row.isAutoGenerated,
      reversesEntryId: row.reversesEntryId,
    },
    ...(args.reason ? { reason: args.reason } : {}),
    ...(args.ip ? { ip: args.ip } : {}),
  })

  return toDto(row)
}

