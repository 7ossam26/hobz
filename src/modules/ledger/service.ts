export interface RecordAdvanceArgs {
  userId: string
  /** The magnitude a human typed. Stored negative — see `signedAmountFor`. */
  amount: MoneyInput
  note: string
  actor: AuditActorRef | null
  cycleDay: number
  at?: Date
  ip?: string
}

/**
 * A سلفة (SPEC §5.5): "recorded whenever, and settle automatically at cycle
 * close because balance is a sum".
 *
 * Note what is *not* here and must never be added: nothing schedules a
 * repayment, nothing tracks an outstanding advance, nothing deducts one at
 * close. The negative entry is the whole mechanism. An advance larger than a
 * month simply leaves the balance negative, and the next cycle's payout is
 * smaller by exactly that much because it is the same sum.
 */
export async function recordAdvance(
  db: Db,
  args: RecordAdvanceArgs,
): Promise<LedgerEntryDto> {
  return appendEntry(db, {
    userId: args.userId,
    type: 'ADVANCE',
    amount: signedAmountFor('ADVANCE', args.amount),
    note: args.note,
    actor: args.actor,
    cycleDay: args.cycleDay,
    auditAction: 'advance.created',
    ...(args.at ? { at: args.at } : {}),
    ...(args.ip ? { ip: args.ip } : {}),
  })
}

