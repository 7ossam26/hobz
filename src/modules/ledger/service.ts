/**
 * modules/ledger/service — the ONE path that writes money.
 *
 * CLAUDE.md invariant 1: "The ledger is append-only. `LedgerEntry` is never
 * updated or deleted. Corrections insert a `REVERSAL`. Balances are always
 * `SUM(amount)` — there is no balance column and you must never add one."
 *
 * Everything in this file is a consequence of that sentence:
 *
 *  - `appendEntry` is the only writer, so the sign rule, the audit row and the
 *    cycle stamp cannot be forgotten by a caller.
 *  - There is no `updateEntry` and no `deleteEntry`, in code or in the
 *    database — the migration installs a trigger that rejects both.
 *  - `balanceFor` is one aggregate over `[userId, createdAt]`. Nothing caches
 *    it, nothing denormalises it, and nothing may.
 */

/** Structural, so it accepts Prisma's `Decimal` without importing its runtime. */
type DecimalLike = { toFixed(dp: number): string }

const moneyOf = (value: DecimalLike | null | undefined): Money =>
  value == null ? zero() : toMoney(value.toFixed(2))

const isUniqueViolation = (error: unknown): boolean =>
  typeof error === 'object' &&
  error !== null &&
  (error as { code?: string }).code === 'P2002'

const ENTRY_SELECT = {
  id: true,
  userId: true,
  cycleId: true,
  type: true,
  amount: true,
  taskId: true,
  note: true,
  isAutoGenerated: true,
  reversesEntryId: true,
  createdById: true,
  createdAt: true,
} as const

interface EntryRow {
  id: string
  userId: string
  cycleId: string | null
  type: string
  amount: DecimalLike
  taskId: string | null
  note: string
  isAutoGenerated: boolean
  reversesEntryId: string | null
  createdById: string | null
  createdAt: Date
}

function toDto(row: EntryRow): LedgerEntryDto {
  return {
    id: row.id,
    userId: row.userId,
    cycleId: row.cycleId,
    type: row.type as LedgerType,
    amount: row.amount.toFixed(2),
    taskId: row.taskId,
    note: row.note,
    isAutoGenerated: row.isAutoGenerated,
    reversesEntryId: row.reversesEntryId,
    createdById: row.createdById,
    createdAt: row.createdAt,
  }
}

