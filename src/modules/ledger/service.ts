export interface BalanceArgs {
  userId: string
  /** Half-open: entries written *at* this instant are excluded. */
  at?: Date
}

/**
 * One indexed aggregate over `[userId, createdAt]`.
 *
 * A person with no entries has a balance of `0.00`, not `null` — the caller
 * rendering a statement must not have to tell "nothing yet" apart from "zero".
 */
export async function balanceFor(db: Db, args: BalanceArgs): Promise<string> {
  const result = await db.ledgerEntry.aggregate({
    _sum: { amount: true },
    where: {
      userId: args.userId,
      ...(args.at ? { createdAt: { lt: args.at } } : {}),
    },
  })

  return toStorageString(moneyOf(result._sum.amount as DecimalLike | null))
}

export interface BalancesArgs {
  userIds: readonly string[]
  at?: Date
}

/** The same aggregate for many people, in one grouped query. */
export async function balancesFor(
  db: Db,
  args: BalancesArgs,
): Promise<Map<string, string>> {
  const ids = [...new Set(args.userIds)]
  const balances = new Map<string, string>(ids.map((id) => [id, '0.00']))
  if (ids.length === 0) return balances

  const grouped = await db.ledgerEntry.groupBy({
    by: ['userId'],
    _sum: { amount: true },
    where: {
      userId: { in: ids },
      ...(args.at ? { createdAt: { lt: args.at } } : {}),
    },
  })
  const rows = grouped as unknown as Array<{
    userId: string
    _sum: { amount: DecimalLike | null }
  }>

  for (const row of rows) {
    balances.set(row.userId, toStorageString(moneyOf(row._sum.amount)))
  }
  return balances
}

