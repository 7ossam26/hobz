import type { LedgerType } from './sign'

/**
 * DTOs crossing out of the module. Money is always a canonical 2dp **string**,
 * never a `number` (CLAUDE.md invariant 2) — the same rule
 * `modules/user/types.ts` follows for `monthlySalary` and
 * `modules/task/types.ts` for `taskValue`.
 */

export interface LedgerPersonDto {
  id: string
  fullName: string
  username: string
}

export interface LedgerEntryDto {
  id: string
  userId: string
  cycleId: string | null
  type: LedgerType
  /** Signed. Debits are negative — see `modules/ledger/sign`. */
  amount: string
  taskId: string | null
  note: string
  isAutoGenerated: boolean
  reversesEntryId: string | null
  createdById: string | null
  createdAt: Date
}

/** An entry with the context a statement row needs to render itself. */
export interface LedgerEntryRowDto extends LedgerEntryDto {
  task: { id: string; title: string } | null
  createdBy: LedgerPersonDto | null
  /** Set when a later `REVERSAL` cancelled this entry out. */
  reversedByEntryId: string | null
}

export interface LedgerPageDto {
  items: LedgerEntryRowDto[]
  total: number
  page: number
  pageSize: number
  /**
   * `SUM(amount)` over everything the filters select — the whole result set,
   * not this page. With one منفّذ and no filters (the مستحقاتي page) that is
   * exactly their balance.
   */
  balance: string
}

/** What the مستحقاتي header shows above the statement. */
export interface LedgerSummaryDto {
  userId: string
  balance: string
  /** Movements attributed to the currently open cycle. */
  currentCycle: {
    id: string
    periodStart: Date
    periodEnd: Date
    /** `EARNING + SALARY`, so the page never has to add two Decimals in JSX. */
    gross: string
    earnings: string
    salary: string
    penalties: string
    bonuses: string
    advances: string
    adjustments: string
  } | null
  /** Sum of `net − paidAmount` across every payout not yet fully paid. */
  outstandingPayouts: string
}
