import { ar } from '@/i18n/ar'
import { recordAudit, type AuditActorRef } from '@/lib/audit'
import type { Db } from '@/lib/db'
import { AppError } from '@/lib/errors'
import { isZero, toMoney } from '@/lib/money'
import { getSetting } from '@/lib/settings'
import type { TaskEventBus } from '@/modules/task/ports'

import { appendEntry, isUniqueViolation, reverseEntry } from './service'
import type { LedgerEntryDto } from './types'

/**
 * modules/ledger/earnings — the subscriber Phase 4 was emitting into a void for.
 *
 * SPEC §5.1: "`APPROVED` is the only event that creates an `EARNING` ledger
 * entry." Phase 4 built the call site, proved the payload in its integration
 * tests, and pointed it at `noopTaskEvents`. This is the other end of that wire,
 * and the shape is unchanged — which is the whole value of having stubbed it.
 *
 * ── Why the handler is idempotent rather than the caller ──────────────────
 *
 * The state machine already refuses `APPROVED → APPROVED`, so a second approval
 * cannot arrive through the UI. What can arrive twice is the *event*: a retry, a
 * replayed job, a transaction that failed after the task update. None of those
 * are visible to the machine, so "approving twice must not double-pay" has to be
 * true here. It is enforced three deep: a read before the write, a partial
 * unique index on `(taskId) WHERE type = 'EARNING'`, and a catch that treats the
 * index's rejection as success rather than as an error.
 */

export interface LedgerTaskEventsArgs {
  /** Settings `payout.cycleDay`, injected (CLAUDE.md invariant 4). */
  cycleDay: number
}

export interface RecordTaskEarningArgs {
  taskId: string
  assigneeId: string | null
  /** `lib/money` storage string, as the event carries it. */
  taskValue: string
  approvedAt: Date
  approvedById: string | null
  cycleDay: number
  ip?: string
}

/**
 * Reasons an approval legitimately pays nobody. Each one writes an audit row
 * rather than returning quietly: "why did nobody get paid for this" must be
 * answerable a month later, and silence is the one answer that never is.
 */
type SkipReason = 'no-assignee' | 'zero-value' | 'assignee-deleted'

async function skip(
  db: Db,
  args: {
    taskId: string
    reason: SkipReason
    actor: AuditActorRef | null
    after: Record<string, unknown>
  },
): Promise<null> {
  await recordAudit(db, {
    actor: args.actor,
    action: 'ledger.earningSkipped',
    entity: 'Task',
    entityId: args.taskId,
    after: { reason: args.reason, ...args.after },
  })
  return null
}

export async function recordTaskEarning(
  db: Db,
  args: RecordTaskEarningArgs,
): Promise<LedgerEntryDto | null> {
  const actor: AuditActorRef | null = args.approvedById ? { id: args.approvedById } : null

  if (!args.assigneeId) {
    return skip(db, {
      taskId: args.taskId,
      reason: 'no-assignee',
      actor,
      after: { taskValue: args.taskValue },
    })
  }

  // A task worth nothing earns nothing. Writing a 0.00 row instead would put a
  // meaningless line on every منفّذ's statement for every internal task, and
  // `appendEntry` refuses zero anyway — a movement of zero is not a movement.
  if (isZero(toMoney(args.taskValue))) {
    return skip(db, {
      taskId: args.taskId,
      reason: 'zero-value',
      actor,
      after: { assigneeId: args.assigneeId, taskValue: args.taskValue },
    })
  }

  const existing = await db.ledgerEntry.findFirst({
    where: { taskId: args.taskId, type: 'EARNING' },
    select: { id: true },
  })
  if (existing) return null

  const assignee = await db.user.findFirst({
    where: { id: args.assigneeId, deletedAt: null },
    select: { id: true },
  })
  if (!assignee) {
    return skip(db, {
      taskId: args.taskId,
      reason: 'assignee-deleted',
      actor,
      after: { assigneeId: args.assigneeId, taskValue: args.taskValue },
    })
  }

  const task = await db.task.findUnique({
    where: { id: args.taskId },
    select: { title: true },
  })

  try {
    return await appendEntry(db, {
      userId: args.assigneeId,
      type: 'EARNING',
      amount: args.taskValue,
      taskId: args.taskId,
      note: ar.ledger.notes.taskEarning.replace('{task}', task?.title ?? ''),
      isAutoGenerated: true,
      actor,
      cycleDay: args.cycleDay,
      at: args.approvedAt,
      ...(args.ip ? { ip: args.ip } : {}),
    })
  } catch (error) {
    // Two emissions raced and the index caught the second. That is the index
    // doing its job, not a failure — unless the write was inside somebody
    // else's transaction, in which case it is already doomed and rethrowing is
    // the only honest answer.
    if (isUniqueViolation(error)) return null
    throw error
  }
}

export interface ReverseTaskEarningArgs {
  taskId: string
  cancelledAt: Date
  cancelledById: string | null
  reason: string
  cycleDay: number
  ip?: string
}

/**
 * SPEC §5.1 makes `APPROVED → CANCELLED` legal, so a cancellation can land
 * after the money did. The earning stays — it happened — and a `REVERSAL`
 * answers it.
 *
 * If the cycle has already been paid out, `reverseEntry` refuses (axis 7) and
 * the cancellation still succeeds: blocking it would trap the task in a status
 * nobody wants over a money question that a `REVERSAL` cannot answer anyway.
 * The refusal is audited so the clawback is somebody's decision rather than
 * nobody's.
 */
export async function reverseTaskEarning(
  db: Db,
  args: ReverseTaskEarningArgs,
): Promise<LedgerEntryDto | null> {
  const earning = await db.ledgerEntry.findFirst({
    where: { taskId: args.taskId, type: 'EARNING' },
    select: { id: true, userId: true },
  })
  if (!earning) return null

  const already = await db.ledgerEntry.findUnique({
    where: { reversesEntryId: earning.id },
    select: { id: true },
  })
  if (already) return null

  const actor: AuditActorRef | null = args.cancelledById
    ? { id: args.cancelledById }
    : null
  const note = ar.ledger.notes.taskCancelled.replace('{reason}', args.reason.trim())

  try {
    return await reverseEntry(db, {
      entryId: earning.id,
      reason: note,
      actor,
      cycleDay: args.cycleDay,
      at: args.cancelledAt,
      isAutoGenerated: true,
      ...(args.ip ? { ip: args.ip } : {}),
    })
  } catch (error) {
    if (
      error instanceof AppError &&
      error.messageKey === 'ledger.errors.cycleAlreadyPaid'
    ) {
      await recordAudit(db, {
        actor,
        action: 'ledger.reversalBlocked',
        entity: 'LedgerEntry',
        entityId: earning.id,
        after: {
          taskId: args.taskId,
          userId: earning.userId,
          reason: 'cycle-already-paid',
        },
        reason: args.reason,
      })
      return null
    }
    throw error
  }
}

/**
 * The bus, with its one business number injected. Services take this; the
 * action layer builds it from Settings.
 */
export function createLedgerTaskEvents(args: LedgerTaskEventsArgs): TaskEventBus {
  return {
    async emit(db, event) {
      // Explicit per-type narrowing, not an if/else-fallthrough: Phase 9 added
      // four more `TaskDomainEvent` variants (assigned, submitted, revision
      // requested, mentioned), and a bare `else` here would have cast one of
      // them to `TaskCancelledEvent` and tried to reverse an earning that was
      // never approved. This bus answers to exactly two event types and
      // ignores the rest — that is its whole contract.
      if (event.type === 'TaskApproved') {
        await recordTaskEarning(db, {
          taskId: event.taskId,
          assigneeId: event.assigneeId,
          taskValue: event.taskValue,
          approvedAt: event.approvedAt,
          approvedById: event.approvedById ?? null,
          cycleDay: args.cycleDay,
        })
        return
      }

      if (event.type === 'TaskCancelled') {
        // Only an approved task ever had an earning to answer for. The event
        // carries that fact precisely so the ledger does not have to
        // re-derive it from a status that has already moved on.
        if (!event.wasApproved) return

        await reverseTaskEarning(db, {
          taskId: event.taskId,
          cancelledAt: event.cancelledAt,
          cancelledById: event.cancelledById ?? null,
          reason: event.reason,
          cycleDay: args.cycleDay,
        })
      }
    },
  }
}

/**
 * The production bus, reading its own setting. Adapters may — services may not
 * (the same split `modules/leave/lookup.ts` makes).
 */
export const ledgerTaskEvents: TaskEventBus = {
  async emit(db, event) {
    const cycleDay = await getSetting('payout.cycleDay')
    await createLedgerTaskEvents({ cycleDay }).emit(db, event)
  },
}
