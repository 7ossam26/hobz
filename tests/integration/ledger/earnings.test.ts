import { describe, expect, it } from 'vitest'

import { SETTINGS_CATALOG } from '@/lib/settings/catalog'
import { createLedgerTaskEvents } from '@/modules/ledger/earnings'
import { balanceFor } from '@/modules/ledger/service'
import { approveTask, cancelTask } from '@/modules/task/service'

import {
  createProject,
  createTask,
  createUser,
  createUserWithPermissions,
  seedPermissionCatalog,
} from '../../factories/db'
import { actorFor } from '../../helpers/actor-from-db'
import { cairo } from '../../helpers/time'
import { testDb } from '../../setup/reset'

const db = testDb()
const CYCLE_DAY = SETTINGS_CATALOG['payout.cycleDay'].default
const NOW = cairo('2026-08-15T10:00')

const events = createLedgerTaskEvents({ cycleDay: CYCLE_DAY })

/**
 * SPEC §5.1: "`APPROVED` is the only event that creates an `EARNING` ledger
 * entry." Phase 4 emitted `TaskApproved` into a no-op bus and proved the
 * payload; this is the subscriber it was waiting for.
 *
 * Every test here goes through `approveTask`/`cancelTask` rather than calling
 * the subscriber directly, because "only approval creates money" is a claim
 * about the *task* module's call sites, not about a handler in isolation.
 */
async function scenario(
  overrides: {
    taskValue?: string
    assigned?: boolean
    status?: 'IN_REVIEW' | 'APPROVED' | 'IN_PROGRESS'
  } = {},
) {
  await seedPermissionCatalog(db)
  const manager = await createUserWithPermissions(db, ['task.approve', 'task.cancel'])
  const worker = await createUser(db)
  const project = await createProject(db, { ownerId: manager.id })
  const task = await createTask(db, {
    projectId: project.id,
    assigneeId: overrides.assigned === false ? null : worker.id,
    status: overrides.status ?? 'IN_REVIEW',
    taskValue: overrides.taskValue ?? '1500.00',
    ...(overrides.status === 'APPROVED' ? { approvedAt: NOW, qualityRating: 4 } : {}),
  })

  return { task, worker, project, manager: await actorFor(db, manager.id) }
}

describe('modules/ledger — الاعتماد يولّد الاستحقاق', () => {
  it('يكتب قيد استحقاق بقيمة المهمة للمنفّذ', async () => {
    const { task, worker, manager } = await scenario({ taskValue: '1500.00' })

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 5 },
    })

    const entries = await db.ledgerEntry.findMany({ where: { userId: worker.id } })
    expect(entries).toHaveLength(1)
    expect(entries[0]).toMatchObject({
      type: 'EARNING',
      taskId: task.id,
      isAutoGenerated: true,
    })
    expect(entries[0]?.amount.toFixed(2)).toBe('1500.00')
    expect(await balanceFor(db, { userId: worker.id })).toBe('1500.00')
  })

  it('ينسب القيد للمنفّذ لا للمعتمِد', async () => {
    const { task, worker, manager } = await scenario()

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    const entry = await db.ledgerEntry.findFirstOrThrow({ where: { taskId: task.id } })
    expect(entry.userId).toBe(worker.id)
    // …and records who caused it, which is a different question.
    expect(entry.createdById).toBe(manager.id)
    expect(await balanceFor(db, { userId: manager.id })).toBe('0.00')
  })

  it('يشرح نفسه بعربية يقرؤها المنفّذ', async () => {
    const { task, manager } = await scenario()

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    const entry = await db.ledgerEntry.findFirstOrThrow({ where: { taskId: task.id } })
    expect(entry.note).toContain(task.title)
    expect(entry.note.trim().length).toBeGreaterThan(0)
  })

  it('يكتب سطر تدقيق للحركة المالية', async () => {
    const { task, manager } = await scenario()

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    const audit = await db.auditLog.findFirst({
      where: { entity: 'LedgerEntry', action: 'ledger.entryCreated' },
    })
    expect(audit).not.toBeNull()
    expect(audit?.actorId).toBe(manager.id)
  })
})

describe('modules/ledger — الاعتماد مرتين لا يضاعف الأجر', () => {
  it('إعادة إطلاق الحدث لا تنتج قيدًا ثانيًا', async () => {
    // The state machine already refuses APPROVED → APPROVED, so the way this
    // fails in production is a retry, a replay, or a job that fires the event
    // again — none of which the machine sees.
    const { task, worker, manager } = await scenario()
    const payload = {
      type: 'TaskApproved' as const,
      taskId: task.id,
      projectId: (await db.task.findUniqueOrThrow({ where: { id: task.id } })).projectId,
      assigneeId: worker.id,
      taskValue: '1500.00',
      qualityRating: 5,
      approvedAt: NOW,
      approvedById: manager.id,
    }

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 5 },
    })
    await events.emit(db, payload)
    await events.emit(db, payload)

    expect(
      await db.ledgerEntry.count({ where: { taskId: task.id, type: 'EARNING' } }),
    ).toBe(1)
    expect(await balanceFor(db, { userId: worker.id })).toBe('1500.00')
  })

  it('لا تنجح محاولتان متزامنتان في كتابة قيدين', async () => {
    // The service checks first; the partial unique index is what makes the
    // check hold when two transactions check at the same time.
    const { task, worker, manager } = await scenario()
    const payload = {
      type: 'TaskApproved' as const,
      taskId: task.id,
      projectId: (await db.task.findUniqueOrThrow({ where: { id: task.id } })).projectId,
      assigneeId: worker.id,
      taskValue: '1500.00',
      qualityRating: 5,
      approvedAt: NOW,
      approvedById: manager.id,
    }

    const results = await Promise.allSettled([
      events.emit(db, payload),
      events.emit(db, payload),
      events.emit(db, payload),
    ])

    expect(results.some((r) => r.status === 'fulfilled')).toBe(true)
    expect(
      await db.ledgerEntry.count({ where: { taskId: task.id, type: 'EARNING' } }),
    ).toBe(1)
    expect(await balanceFor(db, { userId: worker.id })).toBe('1500.00')
  })

  it('يرفض قيد استحقاق ثانٍ لنفس المهمة على مستوى قاعدة البيانات', async () => {
    const { task, worker, manager } = await scenario()
    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 5 },
    })

    await expect(
      db.ledgerEntry.create({
        data: {
          userId: worker.id,
          type: 'EARNING',
          amount: '1500.00',
          taskId: task.id,
          note: 'التفاف',
        },
      }),
    ).rejects.toThrow()
  })
})

describe('modules/ledger — المهام الملغاة لا تولّد أجرًا', () => {
  it('إلغاء مهمة لم تُعتمد لا يكتب أي قيد', async () => {
    const { task, worker, manager } = await scenario({ status: 'IN_PROGRESS' })

    await cancelTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, reason: 'ألغى العميل النطاق' },
    })

    expect(await db.ledgerEntry.count({ where: { userId: worker.id } })).toBe(0)
    expect(await balanceFor(db, { userId: worker.id })).toBe('0.00')
  })

  it('إلغاء مهمة بعد اعتمادها يكتب قيدًا عكسيًا لا حذفًا', async () => {
    // SPEC §5.1 makes APPROVED → CANCELLED legal, so a cancellation can land
    // after the money did. The earning stays; a REVERSAL answers it.
    const { task, worker, manager } = await scenario()
    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 5 },
    })
    expect(await balanceFor(db, { userId: worker.id })).toBe('1500.00')

    await cancelTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, reason: 'العميل ألغى بعد الاعتماد' },
    })

    const entries = await db.ledgerEntry.findMany({
      where: { userId: worker.id },
      orderBy: { createdAt: 'asc' },
    })
    expect(entries.map((e) => e.type)).toEqual(['EARNING', 'REVERSAL'])
    expect(entries[1]?.amount.toFixed(2)).toBe('-1500.00')
    expect(entries[1]?.reversesEntryId).toBe(entries[0]?.id)
    expect(await balanceFor(db, { userId: worker.id })).toBe('0.00')
  })

  it('الإلغاء مرتين لا يكتب عكسين', async () => {
    const { task, worker, manager } = await scenario()
    const projectId = (await db.task.findUniqueOrThrow({ where: { id: task.id } }))
      .projectId

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 5 },
    })
    await cancelTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, reason: 'إلغاء' },
    })
    // Replaying the event, as a retry would.
    await events.emit(db, {
      type: 'TaskCancelled',
      taskId: task.id,
      projectId,
      assigneeId: worker.id,
      wasApproved: true,
      cancelledAt: NOW,
      cancelledById: null as unknown as string,
      reason: 'إلغاء',
    })

    expect(await db.ledgerEntry.count({ where: { type: 'REVERSAL' } })).toBe(1)
    expect(await balanceFor(db, { userId: worker.id })).toBe('0.00')
  })
})

describe('modules/ledger — الحالات الفارغة', () => {
  it('مهمة بلا منفّذ لا تولّد قيدًا ولكنها تُسجَّل', async () => {
    const { task, manager } = await scenario({ assigned: false, status: 'IN_REVIEW' })

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    expect(await db.ledgerEntry.count()).toBe(0)
    // Silence would make "why did nobody get paid for this" unanswerable.
    const audit = await db.auditLog.findFirst({
      where: { action: 'ledger.earningSkipped' },
    })
    expect(audit).not.toBeNull()
    expect(audit?.entityId).toBe(task.id)
  })

  it('مهمة قيمتها صفر لا تولّد قيدًا بصفر', async () => {
    // A movement of zero is not a movement. It would also make every internal
    // task print a meaningless row on the منفّذ's statement.
    const { task, worker, manager } = await scenario({ taskValue: '0.00' })

    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    expect(await db.ledgerEntry.count({ where: { userId: worker.id } })).toBe(0)
    expect(await db.auditLog.count({ where: { action: 'ledger.earningSkipped' } })).toBe(
      1,
    )
  })

  it('إلغاء مهمة معتمدة بلا منفّذ لا ينفجر', async () => {
    const { task, manager } = await scenario({ assigned: false })
    await approveTask(db, {
      actor: manager,
      now: NOW,
      events,
      input: { taskId: task.id, qualityRating: 4 },
    })

    await expect(
      cancelTask(db, {
        actor: manager,
        now: NOW,
        events,
        input: { taskId: task.id, reason: 'إلغاء' },
      }),
    ).resolves.toBeDefined()
    expect(await db.ledgerEntry.count()).toBe(0)
  })
})
