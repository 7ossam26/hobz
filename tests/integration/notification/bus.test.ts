describe('modules/notification/bus — PayoutEventBus', () => {
  it('PayoutApproved وPayoutPaid يصلان لصاحب المستحقات', async () => {
    const worker = await createUser(db)
    const cycle = await createPayoutCycle(db)
    const payout = await createPayout(db, { userId: worker.id, cycleId: cycle.id })

    await notificationPayoutEvents.emit(db, {
      type: 'PayoutApproved',
      payoutId: payout.id,
      userId: worker.id,
      net: '500.00',
      approvedById: 'mgr1',
      at: NOW,
    })
    await notificationPayoutEvents.emit(db, {
      type: 'PayoutPaid',
      payoutId: payout.id,
      userId: worker.id,
      amount: '500.00',
      fullyPaid: true,
      paidById: 'mgr1',
      at: NOW,
    })

    const rows = await db.notification.findMany({
      where: { userId: worker.id },
      orderBy: { type: 'asc' },
    })
    expect(rows.map((r) => r.type).sort()).toEqual(['PAYOUT_APPROVED', 'PAYOUT_PAID'])
    expect(rows.every((r) => r.entityType === 'Payout')).toBe(true)
  })
})

describe('modules/notification/bus — ExtensionEventBus', () => {
  it('ExtensionRequested يصل لمالك المشروع لا لطالب التمديد', async () => {
    const owner = await createUserWithPermissions(db, [])
    const requester = await createUser(db)
    const project = await createProject(db, { ownerId: owner.id })
    const task = await createTask(db, { projectId: project.id, assigneeId: requester.id })

    await notificationExtensionEvents.emit(db, {
      type: 'ExtensionRequested',
      extensionId: 'ex1',
      taskId: task.id,
      taskTitle: task.title,
      requestedById: requester.id,
      oldDueDate: NOW,
      newDueDate: cairo('2026-08-20T10:00'),
      reason: 'انتظار مواد من العميل',
      at: NOW,
    })

    expect(
      await db.notification.count({
        where: { userId: owner.id, type: 'EXTENSION_REQUESTED' },
      }),
    ).toBe(1)
    expect(await db.notification.count({ where: { userId: requester.id } })).toBe(0)
  })

  it('لا يُرسل للمالك عندما يكون هو نفسه طالب التمديد', async () => {
    const ownerRequester = await createUser(db)
    const project = await createProject(db, { ownerId: ownerRequester.id })
    const task = await createTask(db, {
      projectId: project.id,
      assigneeId: ownerRequester.id,
    })

    await notificationExtensionEvents.emit(db, {
      type: 'ExtensionRequested',
      extensionId: 'ex2',
      taskId: task.id,
      taskTitle: task.title,
      requestedById: ownerRequester.id,
      oldDueDate: NOW,
      newDueDate: cairo('2026-08-20T10:00'),
      reason: 'سبب',
      at: NOW,
    })

    expect(await db.notification.count({ where: { userId: ownerRequester.id } })).toBe(0)
  })

  it('ExtensionDecided يصل لطالب التمديد', async () => {
    const requester = await createUser(db)

    await notificationExtensionEvents.emit(db, {
      type: 'ExtensionDecided',
      extensionId: 'ex3',
      taskId: 't1',
      taskTitle: 'تصميم الشعار',
      requestedById: requester.id,
      decision: 'APPROVED',
      newDueDate: cairo('2026-08-20T10:00'),
      decidedById: 'mgr1',
      at: NOW,
    })

    expect(
      await db.notification.count({
        where: { userId: requester.id, type: 'EXTENSION_DECIDED' },
      }),
    ).toBe(1)
  })
})

describe('modules/notification/bus — LatenessEventBus', () => {
  it('التصعيد لمستوى PM يصل لمالك المشروع فقط', async () => {
    const owner = await createUser(db)
    const assignee = await createUser(db)
    const project = await createProject(db, { ownerId: owner.id })
    const task = await createTask(db, { projectId: project.id, assigneeId: assignee.id })

    await notificationLatenessEvents.emit(db, {
      type: 'TaskEscalated',
      taskId: task.id,
      projectId: project.id,
      assigneeId: assignee.id,
      from: 'NONE',
      to: 'PM',
      lateWorkingDays: 2,
      dueDate: NOW,
      at: NOW,
    })

    expect(
      await db.notification.count({
        where: { userId: owner.id, type: 'TASK_ESCALATED' },
      }),
    ).toBe(1)
  })

  it('التصعيد لمستوى ADMIN يصل لمالك المشروع ولكل حاملي project.view.all', async () => {
    await seedPermissionCatalog(db)
    const owner = await createUser(db)
    const manager = await createUserWithPermissions(db, ['project.view.all'])
    const project = await createProject(db, { ownerId: owner.id })
    const task = await createTask(db, { projectId: project.id })

    await notificationLatenessEvents.emit(db, {
      type: 'TaskEscalated',
      taskId: task.id,
      projectId: project.id,
      assigneeId: null,
      from: 'PM',
      to: 'ADMIN',
      lateWorkingDays: 6,
      dueDate: NOW,
      at: NOW,
    })

    for (const userId of [owner.id, manager.id]) {
      expect(
        await db.notification.count({ where: { userId, type: 'TASK_ESCALATED' } }),
      ).toBe(1)
    }
  })

  it('العودة إلى NONE لا تُنشئ إشعارًا', async () => {
    const owner = await createUser(db)
    const project = await createProject(db, { ownerId: owner.id })

    await notificationLatenessEvents.emit(db, {
      type: 'TaskEscalated',
      taskId: 't1',
      projectId: project.id,
      assigneeId: null,
      from: 'PM',
      to: 'NONE',
      lateWorkingDays: 0,
      dueDate: NOW,
      at: NOW,
    })

    expect(await db.notification.count({ where: { userId: owner.id } })).toBe(0)
  })

  it('TaskDueSoon وTaskOverdue يصلان للمنفّذ مع dedupeKey على الموعد', async () => {
    const assignee = await createUser(db)
    const project = await createProject(db, { ownerId: assignee.id })

    await notificationLatenessEvents.emit(db, {
      type: 'TaskDueSoon',
      taskId: 't2',
      projectId: project.id,
      taskTitle: 'مراجعة العقد',
      assigneeId: assignee.id,
      dueDate: NOW,
      at: NOW,
    })
    // A second, identical tick (a job replay) must not double-notify.
    await notificationLatenessEvents.emit(db, {
      type: 'TaskDueSoon',
      taskId: 't2',
      projectId: project.id,
      taskTitle: 'مراجعة العقد',
      assigneeId: assignee.id,
      dueDate: NOW,
      at: NOW,
    })

    expect(
      await db.notification.count({
        where: { userId: assignee.id, type: 'TASK_DUE_SOON' },
      }),
    ).toBe(1)
  })
})
