import { describe, expect, it } from 'vitest'

import { balanceFor } from '@/modules/ledger/service'

import {
  createPenaltyProfile,
  createProject,
  createTask,
  createUser,
} from '../../factories/db'
import {
  activePenalties,
  netPenaltyFor,
  penaltyRows,
  recompute,
  reversalRows,
} from '../../helpers/penalty'
import { cairo } from '../../helpers/time'
import { testDb } from '../../setup/reset'

/**
 * SPEC §5.4's engine, end to end against a real database and the real calendar.
 *
 * ── The canonical scenario, worked out by hand ────────────────────────────
 *
 * 2026-03-01 is a **Sunday**; the default weekend is Friday and Saturday.
 *
 *   dueDate            Sun 2026-03-01 17:00 Cairo
 *   + 24h grace        Mon 2026-03-02 17:00   ← lateness starts counting here
 *   measured at        Thu 2026-03-05 12:00
 *
 * A working day counts when its own Cairo start falls in the half-open window
 * (SPEC §5.3), so Tuesday, Wednesday and Thursday count: **3 working days**.
 *
 * the organization default is `PCT_TASK_VALUE_PER_DAY` at 5%, and the task is worth
 * 1000.00, so:
 *
 *   1000.00 × 5% × 3 = **150.00**
 *
 * Every test below moves exactly one input away from that.
 */

const db = testDb()

const DUE = cairo('2026-03-01T17:00')
const DAY_3 = cairo('2026-03-05T12:00')
const DAY_4 = cairo('2026-03-08T12:00')

const TASK_VALUE = '1000.00'

async function lateTask(
  options: { taskValue?: string; penaltyProfileId?: string | null } = {},
) {
  const owner = await createUser(db)
  const worker = await createUser(db, {
    payType: 'PER_TASK',
    defaultTaskRate: '500.00',
    ...(options.penaltyProfileId ? { penaltyProfileId: options.penaltyProfileId } : {}),
  })
  const project = await createProject(db, { ownerId: owner.id })
  const task = await createTask(db, {
    projectId: project.id,
    assigneeId: worker.id,
    status: 'IN_PROGRESS',
    taskValue: options.taskValue ?? TASK_VALUE,
    dueDate: DUE,
    originalDueDate: DUE,
  })
  return { worker, project, task }
}

describe('recomputeTaskPenalty — أول خصم', () => {
  it('يُدخل خصمًا واحدًا بالمبلغ المحسوب يدويًا', async () => {
    const { worker, task } = await lateTask()

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.outcome).toBe('applied')
    expect(outcome.amount).toBe('150.00')
    expect(outcome.breakdown?.lateWorkingDays).toBe(3)

    const rows = await penaltyRows(db, task.id)
    expect(rows).toHaveLength(1)
    // Debits are negative in the ledger (modules/ledger/sign).
    expect(rows[0]?.amount).toBe('-150.00')
    expect(rows[0]?.isAutoGenerated).toBe(true)
    expect(rows[0]?.userId).toBe(worker.id)
    expect(await balanceFor(db, { userId: worker.id })).toBe('-150.00')
  })

  it('القيد يشرح نفسه: الموعد والمهلة والأيام والمعادلة والمبلغ', async () => {
    const { task } = await lateTask()

    await recompute(db, task.id, { now: DAY_3 })

    const [entry] = await penaltyRows(db, task.id)
    // SPEC §4: "an entry that cannot explain itself is exactly what this
    // product exists to abolish." Every term of the formula is exact, so a
    // منفّذ with a calculator arrives at the same 150.00.
    expect(entry?.note).toContain('1,000.00 × 5% × 3 يوم عمل')
    expect(entry?.note).toContain('150.00')
    expect(entry?.note).toContain('24')
  })

  it('لا يخصم من مهمة سُلّمت في موعدها', async () => {
    const { task } = await lateTask()
    await db.task.update({
      where: { id: task.id },
      data: { status: 'SUBMITTED', submittedAt: cairo('2026-03-01T16:00') },
    })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.outcome).toBe('none')
    expect(await penaltyRows(db, task.id)).toHaveLength(0)
  })
})

describe('recomputeTaskPenalty — إعادة الحساب لا تُعدِّل صفًا أبدًا', () => {
  it('تأخير أكبر: قيد عكسي ثم قيد جديد، والقديم باقٍ كما هو', async () => {
    const { task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })
    const [first] = await penaltyRows(db, task.id)

    // Three more working days pass: Sun 08 is the next boundary after Thu 05,
    // so Fri and Sat contribute nothing and the count reaches 4.
    const outcome = await recompute(db, task.id, { now: DAY_4 })

    expect(outcome.outcome).toBe('recalculated')
    expect(outcome.amount).toBe('200.00')

    const rows = await penaltyRows(db, task.id)
    expect(rows).toHaveLength(2)
    // The original row is byte-for-byte what it was — the append-only trigger
    // would have rejected an UPDATE, and nothing tried one.
    expect(rows[0]?.id).toBe(first?.id)
    expect(rows[0]?.amount).toBe('-150.00')
    expect(rows[0]?.reversed).toBe(true)
    expect(rows[1]?.amount).toBe('-200.00')
    expect(rows[1]?.reversed).toBe(false)

    const reversals = await reversalRows(db, task.id)
    expect(reversals).toHaveLength(1)
    expect(reversals[0]?.amount).toBe('150.00')
    expect(reversals[0]?.reversesEntryId).toBe(first?.id)
    // The reversal says *why*, so a منفّذ reading a credit is not left guessing.
    expect(reversals[0]?.note).toContain('إعادة الحساب اليومية')

    expect(await netPenaltyFor(db, task.id)).toBe('-200.00')
    expect(await activePenalties(db, task.id)).toHaveLength(1)
  })

  it('يترك قيدًا فعّالًا واحدًا فقط مهما تكرّرت إعادة الحساب', async () => {
    const { task } = await lateTask()

    await recompute(db, task.id, { now: DAY_3 })
    await recompute(db, task.id, { now: DAY_4 })
    await recompute(db, task.id, { now: cairo('2026-03-12T12:00') })

    const active = await activePenalties(db, task.id)
    expect(active).toHaveLength(1)
    expect(await penaltyRows(db, task.id)).toHaveLength(3)
    expect(await reversalRows(db, task.id)).toHaveLength(2)
  })
})

describe('recomputeTaskPenalty — بروفايل المنفّذ يتقدّم على الافتراضي', () => {
  it('صيغة ثابتة يومية تحلّ محل النسبة العامة', async () => {
    const profile = await createPenaltyProfile(db, {
      name: 'خصم ثابت',
      mode: 'FIXED_PER_DAY',
      value: '80.00',
    })
    const { task } = await lateTask({ penaltyProfileId: profile.id })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.amount).toBe('240.00')
    expect(outcome.breakdown?.profileName).toBe('خصم ثابت')
    expect(outcome.breakdown?.mode).toBe('FIXED_PER_DAY')
  })

  it('مهلة البروفايل تتقدّم على مهلة المؤسسة', async () => {
    // Zero grace: lateness starts at the deadline itself, so Monday counts too.
    const profile = await createPenaltyProfile(db, {
      mode: 'FIXED_PER_DAY',
      value: '10.00',
      graceHours: 0,
    })
    const { task } = await lateTask({ penaltyProfileId: profile.id })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.breakdown?.graceHours).toBe(0)
    expect(outcome.breakdown?.lateWorkingDays).toBe(4)
    expect(outcome.amount).toBe('40.00')
  })

  it('تجاوز المشروع يتقدّم على مهلة البروفايل', async () => {
    const profile = await createPenaltyProfile(db, {
      mode: 'FIXED_PER_DAY',
      value: '10.00',
      graceHours: 0,
    })
    const { task, project } = await lateTask({ penaltyProfileId: profile.id })
    await db.project.update({
      where: { id: project.id },
      data: { gracePeriodHours: 72 },
    })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.breakdown?.graceHours).toBe(72)
    // Grace to Wed 17:00 leaves only Thursday.
    expect(outcome.breakdown?.lateWorkingDays).toBe(1)
  })

  it('صيغة محذوفة لا تُطبَّق — يعود المنفّذ للافتراضي العام', async () => {
    const profile = await createPenaltyProfile(db, {
      mode: 'FIXED_PER_DAY',
      value: '999.00',
      deletedAt: cairo('2026-02-01T09:00'),
    })
    const { task } = await lateTask({ penaltyProfileId: profile.id })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.breakdown?.profileId).toBeNull()
    expect(outcome.amount).toBe('150.00')
  })
})

describe('recomputeTaskPenalty — لا سقف (متعمَّد)', () => {
  it('يتجاوز الخصم قيمة المهمة نفسها دون قصّ', async () => {
    const { worker, task } = await lateTask({ taskValue: '100.00' })
    const profile = await createPenaltyProfile(db, {
      mode: 'FIXED_PER_DAY',
      value: '500.00',
    })
    await db.user.update({
      where: { id: worker.id },
      data: { penaltyProfileId: profile.id },
    })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    // 500 × 3 = 1500 against a task worth 100. SPEC §5.4: "No cap." The payout
    // floors at zero and the surplus carries — that is the close's job.
    expect(outcome.amount).toBe('1500.00')
    expect(await balanceFor(db, { userId: worker.id })).toBe('-1500.00')
  })
})

describe('recomputeTaskPenalty — ما لا يُحتسب', () => {
  it('مهمة بلا منفّذ: لا خصم، ويُسجَّل السبب', async () => {
    const owner = await createUser(db)
    const project = await createProject(db, { ownerId: owner.id })
    const task = await createTask(db, {
      projectId: project.id,
      assigneeId: null,
      status: 'BACKLOG',
      dueDate: DUE,
      originalDueDate: DUE,
    })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.outcome).toBe('skipped')
    expect(outcome.skipReason).toBe('no-assignee')
    expect(await penaltyRows(db, task.id)).toHaveLength(0)

    const audit = await db.auditLog.findFirst({
      where: { action: 'penalty.skipped', entityId: task.id },
    })
    expect(audit).not.toBeNull()
  })

  it('مهمة بلا قيمة ومنفّذ بلا راتب: لا خصم صامت، بل سبب مسجَّل', async () => {
    const owner = await createUser(db)
    const worker = await createUser(db, {
      payType: 'PER_TASK',
      defaultTaskRate: null,
      monthlySalary: null,
    })
    const project = await createProject(db, { ownerId: owner.id })
    const task = await createTask(db, {
      projectId: project.id,
      assigneeId: worker.id,
      status: 'IN_PROGRESS',
      taskValue: '0.00',
      dueDate: DUE,
      originalDueDate: DUE,
    })

    const outcome = await recompute(db, task.id, { now: DAY_3 })

    expect(outcome.outcome).toBe('skipped')
    expect(outcome.skipReason).toBe('no-basis')
    expect(await penaltyRows(db, task.id)).toHaveLength(0)
  })

  /**
   * The distinction that makes a deduction defensible: money moves on
   * arithmetic somebody can reproduce, and it does not move back because a
   * column went null afterwards. A منفّذ who leaves does not get a refund of a
   * deduction that was correct when it was computed — a human with
   * `penalty.reverse` decides that, with a reason.
   */
  it('حذف المنفّذ لاحقًا لا يُلغي خصمًا سبق احتسابه', async () => {
    const { worker, task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })

    await db.user.update({
      where: { id: worker.id },
      data: { deletedAt: cairo('2026-03-06T09:00') },
    })
    const outcome = await recompute(db, task.id, { now: DAY_4 })

    expect(outcome.outcome).toBe('skipped')
    expect(outcome.skipReason).toBe('assignee-deleted')
    expect(await activePenalties(db, task.id)).toHaveLength(1)
    expect(await netPenaltyFor(db, task.id)).toBe('-150.00')
  })

  it('مهمة ملغاة: التأخير صفر، فيُعكس الخصم بالكامل', async () => {
    const { worker, task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })

    await db.task.update({ where: { id: task.id }, data: { status: 'CANCELLED' } })
    const outcome = await recompute(db, task.id, { now: DAY_4 })

    expect(outcome.outcome).toBe('cleared')
    expect(await activePenalties(db, task.id)).toHaveLength(0)
    expect(await netPenaltyFor(db, task.id)).toBe('0.00')
    expect(await balanceFor(db, { userId: worker.id })).toBe('0.00')
  })
})
