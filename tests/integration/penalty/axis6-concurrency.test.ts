/**
 * docs/TESTING.md §4 axis 6 — concurrency, for the penalty engine and the money
 * paths it drags in behind it.
 *
 * `concurrency.test.ts` next door proves the per-task advisory lock: two
 * recomputations of one مهمة, one writes and one is told `locked`. This file is
 * about everything that lock does *not* cover, because the engine is not the
 * only writer on the path it takes:
 *
 *  - `ensureOpenCycle` runs on the first money write of the agency's life, and
 *    two transactions arriving there together is not an exotic case — it is the
 *    first night the engine ever runs.
 *  - `reversePenaltyOrBonus` takes **no** lock at all. A manager reversing a
 *    خصم by hand while the nightly sweep recomputes the same مهمة is two writers
 *    aiming at one row with nothing between them but a unique index.
 *  - A manual خصم and an automatic one are separate decisions about the same
 *    مهمة, and `isAutoGenerated` is the only thing keeping the engine's hands
 *    off the manager's.
 *
 * Every test orders its two sides with a small delay so one has demonstrably
 * taken the lock first, and asserts on the **set** of outcomes and on the money
 * that settled — never on which caller won, which is a property of the
 * connection pool.
 *
 * ── The canonical scenario (shared with engine.test.ts) ───────────────────
 *
 *   2026-03-01 is a Sunday; the default weekend is Friday and Saturday.
 *   due Sun 2026-03-01 17:00 + 24h grace → lateness counts from Mon 17:00.
 *   At Thu 2026-03-05 that is 3 working days; at Sun 2026-03-08 it is 4.
 *
 * The rate, the grace and the mode all come from `SETTINGS_CATALOG` via
 * `PENALTY_DEFAULTS`, and so do the expected amounts below — docs/TESTING.md §5:
 * a Settings change must break the suite loudly, not silently change what it
 * means.
 */

const db = testDb()

const DUE = cairo('2026-03-01T17:00')
/** Three working days late. */
const DAY_3 = cairo('2026-03-05T12:00')
/** Four working days late. */
const DAY_4 = cairo('2026-03-08T12:00')
/** SPEC §5.4's "runs daily (03:00 Cairo)", on the same third day. */
const NIGHT = cairo('2026-03-05T03:00')

const TASK_VALUE = '1000.00'
const RATE = SETTINGS_CATALOG['penalty.defaultValue'].default

/** The agency's default formula worked by hand: قيمة المهمة × النسبة × أيام. */
const owed = (lateWorkingDays: number): string =>
  toStorageString(mul(pct(TASK_VALUE, RATE), lateWorkingDays))

/** The same figure as the ledger stores it — debits are negative. */
const charged = (lateWorkingDays: number): string =>
  toStorageString(negate(owed(lateWorkingDays)))

const after = (ms: number): Promise<void> =>
  new Promise((resolve) => setTimeout(resolve, ms))

async function lateTask() {
  const owner = await createUser(db)
  const worker = await createUser(db, { payType: 'PER_TASK' })
  const project = await createProject(db, { ownerId: owner.id })
  const task = await createTask(db, {
    projectId: project.id,
    assigneeId: worker.id,
    status: 'IN_PROGRESS',
    taskValue: TASK_VALUE,
    dueDate: DUE,
    originalDueDate: DUE,
  })
  return { worker, task }
}

async function manager(): Promise<Actor> {
  await seedPermissionCatalog(db)
  const user = await createUserWithPermissions(db, ['penalty.create', 'penalty.reverse'])
  return actorFor(db, user.id)
}

/**
 * A committed OPEN cycle covering March 2026.
 *
 * Every test except the first one wants the *penalty* paths contended and not
 * the cycle-opening path underneath them. With a cycle already there,
 * `ensureOpenCycle` returns it without taking a lock, so a collision anywhere
 * below is the engine's and not the ledger's.
 */
async function openMarchCycle(): Promise<void> {
  await createPayoutCycle(db, {
    periodStart: cairo('2026-02-28T23:59'),
    periodEnd: cairo('2026-03-28T23:59'),
    status: 'OPEN',
  })
}

/**
 * One recomputation inside its own interactive transaction, as production does.
 *
 * `holdMs` keeps the transaction — and therefore every lock it took — open long
 * enough for the other side to collide with it. Slept in the *database*: the
 * locks belong to the Postgres transaction, and a `setTimeout` here would not
 * stop Prisma finishing it. `::text` because `pg_sleep` returns `void`, which
 * Prisma cannot decode.
 */
function recomputeInTransaction(
  taskId: string,
  now: Date,
  holdMs = 0,
): Promise<PenaltyRecomputeResult> {
  return db.$transaction(async (tx) => {
    const outcome = await recomputeTaskPenalty(tx, {
      taskId,
      calendar: calendarFor(tx),
      settings: PENALTY_DEFAULTS,
      cycleDay: CYCLE_DAY,
      cause: 'scheduled',
      now,
      actor: null,
    })
    if (holdMs > 0) {
      await tx.$queryRaw`SELECT pg_sleep(${holdMs / 1000}::double precision)::text AS slept`
    }
    return outcome
  })
}

/** A manager's reversal, in its own transaction, held open the same way. */
function reverseInTransaction(entryId: string, reason: string, actor: Actor, holdMs = 0) {
  return db.$transaction(async (tx) => {
    const outcome = await reversePenaltyOrBonus(tx, {
      entryId,
      reason,
      actor,
      cycleDay: CYCLE_DAY,
      at: DAY_4,
    })
    if (holdMs > 0) {
      await tx.$queryRaw`SELECT pg_sleep(${holdMs / 1000}::double precision)::text AS slept`
    }
    return outcome
  })
}

/** The REVERSAL rows on a مهمة, with the flag that says who wrote each one. */
async function reversalsOn(taskId: string) {
  return db.ledgerEntry.findMany({
    where: { taskId, type: 'REVERSAL' },
    orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    select: { id: true, note: true, isAutoGenerated: true, reversesEntryId: true },
  })
}

const fulfilled = (settled: readonly PromiseSettledResult<unknown>[]): number =>
  settled.filter((outcome) => outcome.status === 'fulfilled').length

describe('أول كتابتين ماليتين متزامنتين بلا دورة صرف', () => {
  /**
   * Two transactions, two مهام, two منفّذين, and neither has ever been paid
   * anything — so both reach `ensureOpenCycle` and both find nothing to attach
   * to. This is the collision the blocking lock in `modules/payout/cycle` was
   * added for: before it, the loser's INSERT hit `payout_cycles_single_open`,
   * which aborts the whole transaction, and Postgres then refuses the recovery
   * read with `25P02`. A منفّذ's deduction disappeared with the transaction.
   */
  async function twoFirstWrites() {
    const a = await lateTask()
    const b = await lateTask()

    const settled = await Promise.allSettled([
      recomputeInTransaction(a.task.id, DAY_3, 400),
      // Ordered, not raced: the first has demonstrably created the cycle and is
      // still holding it uncommitted when the second asks for one.
      after(80).then(() => recomputeInTransaction(b.task.id, DAY_3)),
    ])

    return { a, b, settled }
  }

  it('تفتحان دورة صرف واحدة، وكلا القيدين منسوبان إليها', async () => {
    expect(await db.payoutCycle.count()).toBe(0)

    await twoFirstWrites()

    // Two open cycles would be two answers to "which دورة is this قيد in", and
    // the close would settle exactly one of them.
    expect(await db.payoutCycle.count()).toBe(1)
    expect(await db.payoutCycle.count({ where: { status: 'OPEN' } })).toBe(1)

    const entries = await db.ledgerEntry.findMany({
      where: { type: 'PENALTY' },
      select: { cycleId: true },
    })
    // A قيد with no دورة appears on no statement at all.
    expect(entries).toHaveLength(2)
    expect(entries.every((entry) => entry.cycleId !== null)).toBe(true)
    expect(new Set(entries.map((entry) => entry.cycleId)).size).toBe(1)
  })

  it('لا تسقط المعاملة الخاسرة: كلا المنفّذين يُخصم منهما بالكامل', async () => {
    const { a, b, settled } = await twoFirstWrites()

    // The loser must wait and adopt the winner's دورة, not die. A deduction lost
    // to a transaction abort is a منفّذ who was late and was never charged, with
    // nothing anywhere saying so.
    expect(fulfilled(settled)).toBe(2)
    expect(await netPenaltyFor(db, a.task.id)).toBe(charged(3))
    expect(await netPenaltyFor(db, b.task.id)).toBe(charged(3))
    expect(await balanceFor(db, { userId: a.worker.id })).toBe(charged(3))
    expect(await balanceFor(db, { userId: b.worker.id })).toBe(charged(3))
  })
})

describe('القيد الواحد لا يُعكس مرتين مهما تسابق عليه كاتبان', () => {
  it('إعادتا حساب تريدان عكس القيد نفسه تُنتجان قيدًا عكسيًا واحدًا', async () => {
    // Two defences stand behind this, and the assertion is deliberately on the
    // outcome rather than on which one fired: the per-task lock stops the second
    // writer before it reads, and `ledger_entries_reversesEntryId_key` would
    // stop it at the INSERT if the lock ever regressed. Either way the منفّذ is
    // credited back exactly once.
    const { worker, task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })
    const [original] = await penaltyRows(db, task.id)

    const [first, second] = await Promise.all([
      recomputeInTransaction(task.id, DAY_4, 400),
      after(80).then(() => recomputeInTransaction(task.id, DAY_4)),
    ])

    expect([first.outcome, second.outcome].sort()).toEqual(['locked', 'recalculated'])

    const reversals = await reversalsOn(task.id)
    expect(reversals).toHaveLength(1)
    expect(reversals[0]?.reversesEntryId).toBe(original?.id)

    // One active خصم and one net figure, which is what SPEC §5.4's "exactly one
    // active auto PENALTY entry per task" means once the dust settles.
    expect(await activePenalties(db, task.id)).toHaveLength(1)
    expect(await netPenaltyFor(db, task.id)).toBe(charged(4))
    expect(await balanceFor(db, { userId: worker.id })).toBe(charged(4))
  })
})

describe('عكس يدوي يسابق إعادة حساب آلية على المهمة نفسها', () => {
  async function accrued() {
    await openMarchCycle()
    const { worker, task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })
    const [entry] = await penaltyRows(db, task.id)
    return { worker, task, entryId: entry!.id }
  }

  it('قرار المدير يسبق: عكسه هو الوحيد ولا تكتب المحاولة الآلية شيئًا', async () => {
    // `reversePenaltyOrBonus` takes no advisory lock — it is a human decision on
    // one قيد, not a sweep — so nothing stops the engine reaching the same row.
    // The unique index does, and the engine's whole transaction rolls back with
    // it, which is the direction to fail in: the منفّذ ends up un-charged rather
    // than charged twice for one late delivery.
    const { worker, task, entryId } = await accrued()
    const actor = await manager()
    const reason = 'تأخر العميل في اعتماد النص، والمنفّذ لا ذنب له'

    const settled = await Promise.allSettled([
      reverseInTransaction(entryId, reason, actor, 400),
      after(80).then(() => recomputeInTransaction(task.id, DAY_4)),
    ])

    expect(fulfilled(settled)).toBe(1)

    const reversals = await reversalsOn(task.id)
    expect(reversals).toHaveLength(1)
    expect(reversals[0]?.reversesEntryId).toBe(entryId)
    // The manager's own sentence, verbatim — the only explanation the منفّذ gets.
    expect(reversals[0]?.isAutoGenerated).toBe(false)
    expect(reversals[0]?.note).toBe(reason)

    // The engine wrote nothing at all: no replacement خصم, no partial trail.
    expect(await penaltyRows(db, task.id)).toHaveLength(1)
    expect(await activePenalties(db, task.id)).toHaveLength(0)
    expect(await netPenaltyFor(db, task.id)).toBe('0.00')
    expect(await balanceFor(db, { userId: worker.id })).toBe('0.00')
  })

  it('إعادة الحساب تسبق: عكسها هو الوحيد والخصم الجديد قائم', async () => {
    // The mirror image, and it must settle just as cleanly: the manager's click
    // arrives a moment too late and is refused, rather than crediting a قيد the
    // engine has already reversed and replaced — which would hand the منفّذ back
    // money they still owe.
    const { worker, task, entryId } = await accrued()
    const actor = await manager()

    const settled = await Promise.allSettled([
      recomputeInTransaction(task.id, DAY_4, 400),
      after(80).then(() =>
        reversePenaltyOrBonus(db, {
          entryId,
          reason: 'قرار الإدارة بإلغاء الخصم',
          actor,
          cycleDay: CYCLE_DAY,
          at: DAY_4,
        }),
      ),
    ])

    expect(fulfilled(settled)).toBe(1)

    const reversals = await reversalsOn(task.id)
    expect(reversals).toHaveLength(1)
    expect(reversals[0]?.reversesEntryId).toBe(entryId)
    expect(reversals[0]?.isAutoGenerated).toBe(true)

    expect(await activePenalties(db, task.id)).toHaveLength(1)
    expect(await netPenaltyFor(db, task.id)).toBe(charged(4))
    expect(await balanceFor(db, { userId: worker.id })).toBe(charged(4))
  })
})

describe('خصمان يدويان متزامنان لنفس المنفّذ', () => {
  const FIRST = '200.00'
  const SECOND = '75.00'

  it('قراران منفصلان يُسجَّلان كلاهما والرصيد مجموعهما بالضبط', async () => {
    // Nothing here is a duplicate to be collapsed. Two managers deducting from
    // one منفّذ in the same minute are two judgements about two things, and
    // de-duplicating them would silently forgive one — the opposite failure to
    // the engine's, and just as wrong.
    await openMarchCycle()
    const actor = await manager()
    const worker = await createUser(db, { payType: 'PER_TASK' })

    const [first, second] = await Promise.all([
      createManualPenalty(db, {
        userId: worker.id,
        amount: FIRST,
        reason: 'غياب يومين دون إخطار مسبق',
        actor,
        cycleDay: CYCLE_DAY,
        at: DAY_3,
      }),
      createManualPenalty(db, {
        userId: worker.id,
        amount: SECOND,
        reason: 'تسليم ناقص لملفات المصدر',
        actor,
        cycleDay: CYCLE_DAY,
        at: DAY_3,
      }),
    ])

    expect(first.outcome).toBe('applied')
    expect(second.outcome).toBe('applied')
    expect(first.entryId).not.toBe(second.entryId)

    expect(await balanceFor(db, { userId: worker.id })).toBe(
      toStorageString(negate(add(FIRST, SECOND))),
    )
    // Two decisions, two audit rows: "who decided this, and why" has to stay
    // answerable for each of them separately (CLAUDE.md invariant 7).
    expect(
      await db.auditLog.count({
        where: { entity: 'LedgerEntry', action: 'penalty.created' },
      }),
    ).toBe(2)
  })
})

describe('خصم يدوي وخصم آلي على المهمة نفسها في اللحظة نفسها', () => {
  it('اليدوي ينجو من إعادة الحساب الآلية سليمًا', async () => {
    // The engine reads the world before the manager's خصم exists and writes into
    // the world after it does. `isAutoGenerated: false` is the only thing that
    // keeps `findActiveAutoPenalties` from finding the manager's row and
    // reversing a decision it did not make.
    await openMarchCycle()
    const { worker, task } = await lateTask()
    const actor = await manager()
    const MANUAL = '90.00'

    const [auto] = await Promise.all([
      recomputeInTransaction(task.id, DAY_3, 400),
      after(80).then(() =>
        createManualPenalty(db, {
          userId: worker.id,
          taskId: task.id,
          amount: MANUAL,
          reason: 'تسليم بلا مراجعة إملائية',
          actor,
          cycleDay: CYCLE_DAY,
          at: DAY_3,
        }),
      ),
    ])

    expect(auto.outcome).toBe('applied')

    const rows = await penaltyRows(db, task.id)
    expect(rows).toHaveLength(2)
    expect(rows.filter((row) => row.reversed)).toHaveLength(0)

    const manual = rows.filter((row) => !row.isAutoGenerated)
    expect(manual).toHaveLength(1)
    expect(manual[0]?.amount).toBe(toStorageString(negate(MANUAL)))

    // The engine still sees exactly one entry of its own — the manager's is
    // invisible to it, in both directions.
    expect(await activePenalties(db, task.id)).toHaveLength(1)
    expect(await balanceFor(db, { userId: worker.id })).toBe(
      toStorageString(negate(add(owed(3), MANUAL))),
    )
  })
})

describe('الوظيفة الليلية تصطدم بإعادة حساب تحتجز قفل مهمة واحدة', () => {
  /**
   * Hold one مهمة's per-task lock with a **real** recomputation for the duration
   * of `body`.
   *
   * A promise gate rather than sleeps on both sides: the lock is provably held
   * before the sweep starts and released only after it settles, so this asserts
   * a real contention instead of a timing coincidence that passes on a fast
   * machine and hangs on a slow one.
   */
  async function whileTaskRecomputing<T>(
    taskId: string,
    now: Date,
    body: () => Promise<T>,
  ): Promise<{ holder: PenaltyRecomputeResult; result: T }> {
    let signalHeld!: () => void
    let release!: () => void
    const held = new Promise<void>((resolve) => {
      signalHeld = resolve
    })
    const gate = new Promise<void>((resolve) => {
      release = resolve
    })

    const holder = db.$transaction(
      async (tx) => {
        // `.finally`, so a holder that fails signals too: the test then fails on
        // the real error instead of hanging on a gate nobody will ever open.
        const outcome = await recomputeTaskPenalty(tx, {
          taskId,
          calendar: calendarFor(tx),
          settings: PENALTY_DEFAULTS,
          cycleDay: CYCLE_DAY,
          cause: 'manual',
          now,
          actor: null,
        }).finally(signalHeld)
        await gate
        return outcome
      },
      { timeout: 30_000, maxWait: 10_000 },
    )

    await held
    let result: T
    try {
      result = await body()
    } finally {
      release()
    }
    return { holder: await holder, result }
  }

  it('تُسجّل المهمة المحجوزة locked وتُكمل بقية المهام دون أي فشل', async () => {
    // docs/TESTING.md §4 axis 6 names this one by hand: "scheduler firing while
    // a manual recalculation runs". One مهمة being busy must cost that مهمة
    // nothing and cost the other ninety-nine nothing either.
    await openMarchCycle()
    const busy = await lateTask()
    const others = [await lateTask(), await lateTask()]

    const { holder, result } = await whileTaskRecomputing(busy.task.id, NIGHT, () =>
      runPenaltyRecompute(db, { now: NIGHT }),
    )

    expect(holder.outcome).toBe('applied')
    expect(result.scanned).toBe(3)
    expect(result.locked).toBe(1)
    expect(result.applied).toBe(2)
    // `locked` is an outcome, not an error: whoever holds the lock is computing
    // the same target from the same data. Counting it as `failed` would send
    // somebody looking for a deduction that did happen.
    expect(result.failed).toBe(0)

    // The busy مهمة carries exactly the one خصم its holder wrote — not a second
    // one from the sweep.
    expect(await penaltyRows(db, busy.task.id)).toHaveLength(1)
    expect(await netPenaltyFor(db, busy.task.id)).toBe(charged(3))
    for (const other of others) {
      expect(await netPenaltyFor(db, other.task.id)).toBe(charged(3))
    }
  })
})

describe('المحاولة المحجوبة لا تكتب شيئًا إطلاقًا', () => {
  it('لا قيدًا في السجل ولا سطرًا في التدقيق', async () => {
    // Arranged so that the *winner* writes nothing either: it recomputes the
    // figure already in the ledger, which is the idempotent short-circuit and
    // writes not even an audit row. Any row appearing after this race therefore
    // came from the blocked attempt — which measured a later day and so wanted a
    // reversal, a replacement and two audit rows before it was refused.
    const { task } = await lateTask()
    await recompute(db, task.id, { now: DAY_3 })

    const ledgerBefore = await db.ledgerEntry.count()
    const auditBefore = await db.auditLog.count()

    const [winner, blocked] = await Promise.all([
      recomputeInTransaction(task.id, DAY_3, 400),
      after(80).then(() => recomputeInTransaction(task.id, DAY_4)),
    ])

    expect(winner.outcome).toBe('unchanged')
    expect(blocked.outcome).toBe('locked')
    expect(blocked.entryId).toBeNull()
    expect(blocked.reversedEntryId).toBeNull()

    expect(await db.ledgerEntry.count()).toBe(ledgerBefore)
    expect(await db.auditLog.count()).toBe(auditBefore)
    expect(await activePenalties(db, task.id)).toHaveLength(1)
    expect(await netPenaltyFor(db, task.id)).toBe(charged(3))
  })
})
