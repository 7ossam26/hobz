import { describe, expect, it } from 'vitest'

import {
  bonusGrantedMessage,
  extensionDecidedMessage,
  managerDigestMessage,
  moneyReversedMessage,
  penaltyAppliedMessage,
  taskAssignedMessage,
  taskDueSoonMessage,
  taskEscalatedMessage,
  taskOverdueMessage,
} from '@/modules/notification/messages'

const DUE = new Date('2026-08-20T15:00:00.000Z')
const NOW = new Date('2026-08-16T09:00:00.000Z')

/**
 * Pure functions: an event in, Arabic prose and a deep-link target out. No
 * database, no i18n literal outside `i18n/ar.ts` — the same discipline
 * `modules/penalty/breakdown.ts` proves for the deduction text these
 * notifications sit beside on a منفّذ's statement.
 */

describe('modules/notification/messages — رسائل المهام', () => {
  it('taskAssignedMessage يضمّن اسم المهمة والموعد ويشير إلى المهمة', () => {
    const message = taskAssignedMessage({
      type: 'TaskAssigned',
      taskId: 't1',
      projectId: 'p1',
      taskTitle: 'تصميم الشعار',
      assigneeId: 'u1',
      previousAssigneeId: null,
      dueDate: DUE,
      assignedById: 'mgr1',
      at: NOW,
    })

    expect(message.title).toBeTruthy()
    expect(message.body).toContain('تصميم الشعار')
    expect(message.entityType).toBe('Task')
    expect(message.entityId).toBe('t1')
    expect(message.dismissable).toBe(true)
  })

  it('taskDueSoonMessage يشير إلى نفس المهمة', () => {
    const message = taskDueSoonMessage({
      type: 'TaskDueSoon',
      taskId: 't2',
      projectId: 'p1',
      taskTitle: 'مراجعة العقد',
      assigneeId: 'u1',
      dueDate: DUE,
      at: NOW,
    })
    expect(message.body).toContain('مراجعة العقد')
    expect(message.entityId).toBe('t2')
  })

  it('taskOverdueMessage يشير إلى نفس المهمة', () => {
    const message = taskOverdueMessage({
      type: 'TaskOverdue',
      taskId: 't3',
      projectId: 'p1',
      taskTitle: 'تسليم الفيديو',
      assigneeId: 'u1',
      dueDate: DUE,
      lateWorkingDays: 2,
      at: NOW,
    })
    expect(message.body).toContain('تسليم الفيديو')
  })

  it('taskEscalatedMessage يرجع null عند العودة إلى NONE', () => {
    const message = taskEscalatedMessage(
      {
        type: 'TaskEscalated',
        taskId: 't4',
        projectId: 'p1',
        assigneeId: 'u1',
        from: 'PM',
        to: 'NONE',
        lateWorkingDays: 0,
        dueDate: DUE,
        at: NOW,
      },
      'مهمة عالقة',
    )
    expect(message).toBeNull()
  })

  it('taskEscalatedMessage يفرّق بين مستوى PM وADMIN', () => {
    const pm = taskEscalatedMessage(
      {
        type: 'TaskEscalated',
        taskId: 't5',
        projectId: 'p1',
        assigneeId: 'u1',
        from: 'NONE',
        to: 'PM',
        lateWorkingDays: 2,
        dueDate: DUE,
        at: NOW,
      },
      'مهمة متأخرة',
    )
    const admin = taskEscalatedMessage(
      {
        type: 'TaskEscalated',
        taskId: 't5',
        projectId: 'p1',
        assigneeId: 'u1',
        from: 'PM',
        to: 'ADMIN',
        lateWorkingDays: 5,
        dueDate: DUE,
        at: NOW,
      },
      'مهمة متأخرة',
    )

    expect(pm?.title).not.toBe(admin?.title)
    expect(pm?.body).toContain('2')
    expect(admin?.body).toContain('5')
  })
})

describe('modules/notification/messages — رسائل مالية', () => {
  it('penaltyAppliedMessage يستخدم تفصيل الحساب عند توفره', () => {
    const message = penaltyAppliedMessage({
      type: 'PenaltyApplied',
      userId: 'u1',
      entryId: 'e1',
      taskId: 't1',
      amount: '75.00',
      breakdown: {
        taskId: 't1',
        taskTitle: 'تصميم الشعار',
        dueDate: DUE,
        originalDueDate: DUE,
        graceHours: 24,
        effectiveDueDate: DUE,
        measuredAt: NOW,
        lateWorkingDays: 3,
        blockedWorkingDays: 0,
        frozen: true,
        mode: 'PCT_TASK_VALUE_PER_DAY',
        value: '5',
        basis: 'TASK_VALUE',
        basisAmount: '500.00',
        basisFallback: false,
        formula: '500.00 × 5% × 3',
        amount: '75.00',
        profileId: null,
        profileName: null,
        roundIndex: 0,
        revisionCount: 0,
      },
      isAutoGenerated: true,
      dismissable: false,
      at: NOW,
    })

    expect(message.body).toContain('تصميم الشعار')
    expect(message.body).toContain('500.00 × 5% × 3')
    expect(message.dismissable).toBe(false)
    expect(message.entityType).toBe('Task')
  })

  it('penaltyAppliedMessage يستخدم صياغة عامة للخصم اليدوي بلا تفصيل', () => {
    const message = penaltyAppliedMessage({
      type: 'PenaltyApplied',
      userId: 'u1',
      entryId: 'e2',
      taskId: null,
      amount: '100.00',
      breakdown: null,
      isAutoGenerated: false,
      dismissable: false,
      at: NOW,
    })

    expect(message.body).not.toContain('undefined')
    expect(message.entityType).toBeNull()
    expect(message.dismissable).toBe(false)
  })

  it('bonusGrantedMessage يحمل السبب حرفيًا', () => {
    const message = bonusGrantedMessage({
      type: 'BonusGranted',
      userId: 'u1',
      entryId: 'e3',
      amount: '200.00',
      reason: 'إنجاز استثنائي هذا الشهر',
      grantedById: 'mgr1',
      dismissable: true,
      at: NOW,
    })
    expect(message.body).toContain('إنجاز استثنائي هذا الشهر')
    expect(message.dismissable).toBe(true)
  })

  it('moneyReversedMessage يشير إلى المهمة عند وجودها وإلا إلى المستحقات', () => {
    const withTask = moneyReversedMessage({
      type: 'MoneyReversed',
      userId: 'u1',
      entryId: 'e4',
      reversesEntryId: 'e1',
      reversedType: 'PENALTY',
      taskId: 't1',
      amount: '75.00',
      reason: 'اعتماد تمديد',
      reversedById: 'mgr1',
      isAutoGenerated: true,
      dismissable: true,
      at: NOW,
    })
    expect(withTask.entityType).toBe('Task')

    const withoutTask = moneyReversedMessage({
      type: 'MoneyReversed',
      userId: 'u1',
      entryId: 'e5',
      reversesEntryId: 'e2',
      reversedType: 'BONUS',
      taskId: null,
      amount: '50.00',
      reason: 'خطأ في الإدخال',
      reversedById: 'mgr1',
      isAutoGenerated: false,
      dismissable: true,
      at: NOW,
    })
    expect(withoutTask.entityType).toBe('Payout')
  })

  it('extensionDecidedMessage يفرّق بين الاعتماد والرفض', () => {
    const approved = extensionDecidedMessage({
      type: 'ExtensionDecided',
      extensionId: 'ex1',
      taskId: 't1',
      taskTitle: 'تصميم الشعار',
      requestedById: 'u1',
      decision: 'APPROVED',
      newDueDate: DUE,
      decidedById: 'mgr1',
      at: NOW,
    })
    const rejected = extensionDecidedMessage({
      type: 'ExtensionDecided',
      extensionId: 'ex2',
      taskId: 't1',
      taskTitle: 'تصميم الشعار',
      requestedById: 'u1',
      decision: 'REJECTED',
      newDueDate: DUE,
      decidedById: 'mgr1',
      at: NOW,
    })
    expect(approved.title).not.toBe(rejected.title)
  })
})

describe('modules/notification/messages — ملخص المدير', () => {
  it('managerDigestMessage يضمّن الأعداد الثلاثة في النص وفي الحمولة', () => {
    const message = managerDigestMessage({
      overdueCount: 4,
      awaitingApprovalCount: 2,
      atRiskProjectCount: 1,
    })

    expect(message.body).toContain('4')
    expect(message.body).toContain('2')
    expect(message.body).toContain('1')
    expect(message.entityType).toBeNull()
    expect(message.payload).toMatchObject({
      overdueCount: 4,
      awaitingApprovalCount: 2,
      atRiskProjectCount: 1,
    })
  })
})
