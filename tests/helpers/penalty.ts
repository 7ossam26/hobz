import type { PrismaClient } from '@prisma/client'

import { calendarFor } from '@/lib/calendar'
import { SETTINGS_CATALOG } from '@/lib/settings/catalog'
import type { PenaltySettings } from '@/modules/penalty/assess'
import type { MoneyDomainEvent, MoneyEventBus } from '@/modules/penalty/ports'
import {
  recomputeTaskPenalty,
  type PenaltyCause,
  type RecomputeTaskPenaltyArgs,
} from '@/modules/penalty/service'
import type { PenaltyRecomputeResult } from '@/modules/penalty/types'

/**
 * Test seams for the penalty engine.
 *
 * Every business number comes from `SETTINGS_CATALOG`, never from a literal —
 * docs/TESTING.md §5: "read it from Settings in the test too, so a Settings
 * change doesn't silently break the suite's meaning". A test that needs a
 * *different* number states the override explicitly, which is then visibly the
 * thing under test rather than an accident of the defaults.
 */

export const PENALTY_DEFAULTS: PenaltySettings = {
  defaultMode: SETTINGS_CATALOG['penalty.defaultMode'].default,
  defaultValue: SETTINGS_CATALOG['penalty.defaultValue'].default,
  defaultGraceHours: SETTINGS_CATALOG['penalty.defaultGraceHours'].default,
  penalizeRevisionLateness: SETTINGS_CATALOG['penalty.penalizeRevisionLateness'].default,
  workingDaysPerMonth: SETTINGS_CATALOG['calendar.workingDaysPerMonth'].default,
}

export const CYCLE_DAY = SETTINGS_CATALOG['payout.cycleDay'].default

export interface RecomputeOptions {
  now: Date
  settings?: Partial<PenaltySettings>
  cause?: PenaltyCause
  actor?: { id: string } | null
  events?: MoneyEventBus
}

/** One recomputation with the organization defaults, on the real calendar. */
export function recompute(
  db: PrismaClient,
  taskId: string,
  options: RecomputeOptions,
): Promise<PenaltyRecomputeResult> {
  const args: RecomputeTaskPenaltyArgs = {
    taskId,
    calendar: calendarFor(db),
    settings: { ...PENALTY_DEFAULTS, ...options.settings },
    cycleDay: CYCLE_DAY,
    cause: options.cause ?? 'scheduled',
    now: options.now,
    actor: options.actor ?? null,
    ...(options.events ? { events: options.events } : {}),
  }
  return recomputeTaskPenalty(db, args)
}

/** Run the same recomputation `times` times, as the nightly job would. */
export async function recomputeTimes(
  db: PrismaClient,
  taskId: string,
  times: number,
  options: RecomputeOptions,
): Promise<PenaltyRecomputeResult[]> {
  const results: PenaltyRecomputeResult[] = []
  for (let i = 0; i < times; i += 1) {
    results.push(await recompute(db, taskId, options))
  }
  return results
}

/** Records what Phase 9 will subscribe to, so the payload can be asserted on. */
export function recordingEvents(): MoneyEventBus & { events: MoneyDomainEvent[] } {
  const events: MoneyDomainEvent[] = []
  return {
    events,
    async emit(_db, event) {
      events.push(event)
    },
  }
}

/** Every PENALTY row on a task, oldest first, as 2dp magnitudes. */
export async function penaltyRows(db: PrismaClient, taskId: string) {
  const rows = await db.ledgerEntry.findMany({
    where: { taskId, type: 'PENALTY' },
    orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    select: {
      id: true,
      userId: true,
      amount: true,
      note: true,
      isAutoGenerated: true,
      createdAt: true,
      reversedBy: { select: { id: true } },
    },
  })
  return rows.map((r) => ({
    id: r.id,
    userId: r.userId,
    amount: r.amount.toFixed(2),
    note: r.note,
    isAutoGenerated: r.isAutoGenerated,
    createdAt: r.createdAt,
    reversed: r.reversedBy !== null,
  }))
}

/** The unreversed automatic penalties — SPEC §5.4's "active" set. */
export async function activePenalties(db: PrismaClient, taskId: string) {
  return (await penaltyRows(db, taskId)).filter((r) => r.isAutoGenerated && !r.reversed)
}

export async function reversalRows(db: PrismaClient, taskId: string) {
  const rows = await db.ledgerEntry.findMany({
    where: { taskId, type: 'REVERSAL' },
    orderBy: [{ createdAt: 'asc' }, { id: 'asc' }],
    select: { id: true, amount: true, note: true, reversesEntryId: true },
  })
  return rows.map((r) => ({
    id: r.id,
    amount: r.amount.toFixed(2),
    note: r.note,
    reversesEntryId: r.reversesEntryId,
  }))
}

/**
 * The net of every PENALTY and REVERSAL on a task.
 *
 * This is the figure SPEC §5.4's idempotency promise is actually about — "ten
 * runs yield one net penalty" — and it is a `SUM`, because balances always are
 * (CLAUDE.md invariant 1).
 */
export async function netPenaltyFor(db: PrismaClient, taskId: string): Promise<string> {
  const result = await db.ledgerEntry.aggregate({
    _sum: { amount: true },
    where: { taskId, type: { in: ['PENALTY', 'REVERSAL'] } },
  })
  return (result._sum.amount ?? { toFixed: () => '0.00' }).toFixed(2)
}
